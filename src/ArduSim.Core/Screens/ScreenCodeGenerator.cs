using System.Globalization;
using System.Text;

namespace ArduSim.Core.Screens;

/// <param name="Hooks">The whole of <c>ui_hooks.cpp</c>: what was there, plus the stubs that were missing.</param>
public sealed record GeneratedScreens(string Header, string Source, string Hooks);

/// <summary>
/// Plain, readable C++ from the model (ADR-019): a <c>switch</c> per screen for drawing and for events,
/// no heap and no runtime to learn. The sketch calls <c>uiBegin()</c> and <c>uiUpdate()</c>.
/// </summary>
public static class ScreenCodeGenerator
{
    public const string HeaderFile = "ui_screens.h";
    public const string SourceFile = "ui_screens.cpp";
    public const string HooksFile = "ui_hooks.cpp";

    private const string Banner = "// Generated by ArduSim from screens.json: edit it on the Экраны tab. Changes made here are overwritten.\n";
    private const int RefreshMs = 250;
    private const int DebounceMs = 20;

    public static GeneratedScreens Generate(ScreenDocument document, ScreenWiring wiring, string? existingHooks)
    {
        ArgumentNullException.ThrowIfNull(document);
        ArgumentNullException.ThrowIfNull(wiring);
        var generator = new Generator(document, wiring);
        return new GeneratedScreens(generator.Header(), generator.Source(), generator.Hooks(existingHooks));
    }

    /// <summary>A C++ identifier from a name a person gave.</summary>
    public static string Identifier(string name)
    {
        ArgumentNullException.ThrowIfNull(name);
        var id = new StringBuilder(name.Length);
        foreach (char c in name)
        {
            id.Append(char.IsAsciiLetterOrDigit(c) ? c : '_');
        }

        return id.Length == 0 || char.IsAsciiDigit(id[0]) ? "s" + id : id.ToString();
    }

    private static string Upper(string name) => Identifier(name).ToUpperInvariant();

    private static string Literal(string text) => "\"" + ScreenCodeEdits.Escape(text, '"') + "\"";

    private static string CharLiteral(string text) => "'" + ScreenCodeEdits.Escape(text.Length > 0 ? text[..1] : " ", '\'') + "'";

    private static string N(int value) => value.ToString(CultureInfo.InvariantCulture);

    private sealed class Generator(ScreenDocument document, ScreenWiring wiring)
    {
        private readonly ScreenDisplay _display = document.Display;

        private bool IsLcd => _display.Family == DisplayFamily.CharLcd;

        private string D => _display.Variable;

        private bool HasValues => document.Screens.Any(s => s.Elements.Any(e => e.Kind == ElementKind.Value));

        private bool HasTimeouts => document.Screens.Any(s => s.Transitions.Any(t => t.Trigger.Kind == TriggerKind.Timeout));

        private IEnumerable<ScreenTransition> AllTransitions => document.Screens.SelectMany(s => s.Transitions).Concat(document.FromAnywhere);

        private IEnumerable<ScreenTrigger> AllTriggers =>
            AllTransitions.Select(t => t.Trigger).Concat(document.Screens.Where(s => s.Menu is not null).SelectMany(s => new[] { s.Menu!.Up, s.Menu.Down, s.Menu.Select }).OfType<ScreenTrigger>());

        private static string? EventName(ScreenTrigger trigger) => trigger.Kind switch
        {
            TriggerKind.Button => "UI_ON_" + Upper(trigger.Part),
            TriggerKind.Key => "UI_ON_KEY_" + KeyName(trigger.Value),
            TriggerKind.EncoderLeft => "UI_ON_" + Upper(trigger.Part) + "_LEFT",
            TriggerKind.EncoderRight => "UI_ON_" + Upper(trigger.Part) + "_RIGHT",
            TriggerKind.EncoderPress => "UI_ON_" + Upper(trigger.Part) + "_PRESS",
            TriggerKind.Event => "UI_ON_" + Upper(trigger.Value),
            _ => null,
        };

        private static string KeyName(string key) => key switch
        {
            "#" => "HASH",
            "*" => "STAR",
            _ => Upper(key),
        };

        private string[] Events => [.. AllTriggers.Select(EventName).OfType<string>().Distinct(StringComparer.Ordinal)];

        private string[] ValueHooks => [.. document.Screens.SelectMany(s => s.Elements).Where(e => e.Kind == ElementKind.Value).Select(e => Identifier(e.Text)).Distinct(StringComparer.Ordinal)];

        private string[] ActionHooks => [.. document.Screens.Where(s => s.Menu is not null).SelectMany(s => s.Menu!.Items).Where(i => i.Action.Length > 0).Select(i => Identifier(i.Action)).Distinct(StringComparer.Ordinal)];

        private string DisplayType => _display.Existing && _display.TypeName.Length > 0 ? _display.TypeName : _display.Library switch
        {
            DisplayLibrary.LiquidCrystal => "LiquidCrystal",
            DisplayLibrary.LiquidCrystalI2c => "LiquidCrystal_I2C",
            DisplayLibrary.AdafruitSsd1306 => "Adafruit_SSD1306",
            DisplayLibrary.AdafruitSh110x => "Adafruit_SH1106G",
            DisplayLibrary.U8g2 => U8g2Type,
            _ => $"GyverOLED<{GyverModel}, OLED_BUFFER>",
        };

        private string U8g2Type
        {
            get
            {
                string controller = wiring.Controller == "sh1106" ? "SH1106" : wiring.Controller == "ssd1309" ? "SSD1309" : "SSD1306";
                string bus = wiring.OledSpiPins.Count > 0 ? "4W_HW_SPI" : "HW_I2C";
                string panel = wiring.Controller == "ssd1309" ? "NONAME0" : "NONAME";
                return $"U8G2_{controller}_{N(_display.Width)}X{N(_display.Height)}_{panel}_F_{bus}";
            }
        }

        private string GyverModel => wiring.Controller == "sh1106" ? "SSH1106_128x64" : $"SSD1306_{N(_display.Width)}x{N(_display.Height)}";

        private string Include => _display.Library switch
        {
            DisplayLibrary.LiquidCrystal => "LiquidCrystal.h",
            DisplayLibrary.LiquidCrystalI2c => "LiquidCrystal_I2C.h",
            DisplayLibrary.AdafruitSsd1306 => "Adafruit_SSD1306.h",
            DisplayLibrary.AdafruitSh110x => "Adafruit_SH110X.h",
            DisplayLibrary.U8g2 => "U8g2lib.h",
            _ => "GyverOLED.h",
        };

        private string Construction()
        {
            string address = "0x" + wiring.Address.ToString("X2", CultureInfo.InvariantCulture);
            bool spi = wiring.OledSpiPins.Count == 3;
            int dc = spi ? wiring.OledSpiPins[0] : -1;
            int reset = spi ? wiring.OledSpiPins[1] : -1;
            int cs = spi ? wiring.OledSpiPins[2] : -1;
            return _display.Library switch
            {
                DisplayLibrary.LiquidCrystal => $"{D}({string.Join(", ", wiring.LcdPins.Select(N))})",
                DisplayLibrary.LiquidCrystalI2c => $"{D}({address}, {N(_display.Width)}, {N(_display.Height)})",
                DisplayLibrary.AdafruitSsd1306 when spi => $"{D}({N(_display.Width)}, {N(_display.Height)}, &SPI, {N(dc)}, {N(reset)}, {N(cs)})",
                DisplayLibrary.AdafruitSh110x when spi => $"{D}({N(_display.Width)}, {N(_display.Height)}, &SPI, {N(dc)}, {N(reset)}, {N(cs)})",
                DisplayLibrary.AdafruitSsd1306 or DisplayLibrary.AdafruitSh110x => $"{D}({N(_display.Width)}, {N(_display.Height)}, &Wire, -1)",
                DisplayLibrary.U8g2 when spi => $"{D}(U8G2_R0, {N(cs)}, {N(dc)}, {N(reset)})",
                DisplayLibrary.U8g2 => $"{D}(U8G2_R0, U8X8_PIN_NONE)",
                _ => D,
            };
        }

        private string[] BeginDisplay()
        {
            string address = "0x" + wiring.Address.ToString("X2", CultureInfo.InvariantCulture);
            return _display.Library switch
            {
                DisplayLibrary.LiquidCrystal => [$"{D}.begin({N(_display.Width)}, {N(_display.Height)});"],
                DisplayLibrary.LiquidCrystalI2c => [$"{D}.init();", $"{D}.backlight();"],
                DisplayLibrary.AdafruitSsd1306 => [$"{D}.begin(SSD1306_SWITCHCAPVCC, {address});"],
                DisplayLibrary.AdafruitSh110x => [$"{D}.begin({address}, true);"],
                DisplayLibrary.U8g2 => [$"{D}.begin();"],
                _ => [$"{D}.init();"],
            };
        }

        public string Header()
        {
            var o = new StringBuilder(Banner);
            o.Append("#pragma once\n#include <Arduino.h>\n");
            o.Append("#include <").Append(Include).Append(">\n\n");
            o.Append("enum UiScreen : uint8_t {\n");
            foreach (ScreenNode screen in document.Screens)
            {
                o.Append("  UI_").Append(Upper(screen.Id)).Append(",\n");
            }

            o.Append("  UI_SCREEN_COUNT\n};\n\n");
            o.Append("enum UiEvent : uint8_t {\n  UI_NO_EVENT,\n");
            foreach (string name in Events)
            {
                o.Append("  ").Append(name).Append(",\n");
            }

            o.Append("};\n\n");
            o.Append("extern ").Append(DisplayType).Append(' ').Append(D).Append(";\n\n");
            o.Append("// Call uiBegin() from setup() and uiUpdate() from loop().\n");
            o.Append("void uiBegin();\nvoid uiUpdate();\n\n");
            o.Append("// For your own logic: go to a screen, send an event, redraw, ask where it is.\n");
            o.Append("void uiGoTo(UiScreen screen);\nvoid uiSend(UiEvent event);\nvoid uiRedraw();\nUiScreen uiCurrent();\n");
            if (ValueHooks.Length + ActionHooks.Length > 0)
            {
                o.Append("\n// Written in ").Append(HooksFile).Append(": what the screens show and do.\n");
                foreach (string hook in ValueHooks)
                {
                    o.Append("void uiValue_").Append(hook).Append("(char* out, uint8_t size);\n");
                }

                foreach (string hook in ActionHooks)
                {
                    o.Append("void uiAction_").Append(hook).Append("();\n");
                }
            }

            return o.ToString();
        }

        public string Source()
        {
            var o = new StringBuilder(Banner);
            o.Append("#include \"").Append(HeaderFile).Append("\"\n");
            if (wiring.Inputs.Any(i => i.Kind == ScreenInputKind.Keypad))
            {
                o.Append("#include <Keypad.h>\n");
            }

            o.Append('\n');
            if (!_display.Existing)
            {
                o.Append(DisplayType).Append(' ').Append(Construction()).Append(";\n\n");
            }

            o.Append("static UiScreen uiScreen = UI_").Append(Upper(document.Start)).Append(";\n");
            if (HasTimeouts)
            {
                o.Append("static uint32_t uiEnteredAt;\n");
            }

            if (HasValues)
            {
                o.Append("static uint32_t uiValuesAt;\n");
            }

            if (document.Screens.Any(s => s.Menu is not null))
            {
                o.Append("static uint8_t uiMenuIndex;\nstatic uint8_t uiMenuTop;\n");
            }

            o.Append('\n');
            Helpers(o);
            Menus(o);
            Drawing(o);
            if (HasValues)
            {
                Values(o);
            }

            Enter(o);
            Events2(o);
            Inputs(o);
            Begin(o);
            Update(o);
            return o.ToString();
        }

        private void Helpers(StringBuilder o)
        {
            o.Append("// Text and values go through these, so that the screens below say only what and where.\n");
            if (_display.Library == DisplayLibrary.GyverOled)
            {
                o.Append("static void uiAt(int x, int y, int size) {\n  ").Append(D).Append(".setScale(size);\n  ").Append(D).Append(".setCursorXY(x, y);\n}\n\n");
            }
            else if (_display.Library == DisplayLibrary.U8g2)
            {
                o.Append("static void uiAt(int x, int y, int size) {\n  (void)size;\n  ").Append(D).Append(".setFont(u8g2_font_6x10_tf);\n  ").Append(D).Append(".setFontPosTop();\n  ").Append(D).Append(".setCursor(x, y);\n}\n\n");
            }
            else if (IsLcd)
            {
                o.Append("static void uiAt(int x, int y, int size) {\n  (void)size;\n  ").Append(D).Append(".setCursor(x, y);\n}\n\n");
            }
            else
            {
                o.Append("static void uiAt(int x, int y, int size) {\n  ").Append(D).Append(".setTextColor(").Append(White).Append(");\n  ").Append(D).Append(".setTextSize(size);\n  ").Append(D).Append(".setCursor(x, y);\n}\n\n");
            }

            o.Append("static void uiClear() {\n  ").Append(D).Append(_display.Library switch
            {
                DisplayLibrary.U8g2 => ".clearBuffer();",
                DisplayLibrary.GyverOled => ".clear();",
                DisplayLibrary.AdafruitSsd1306 or DisplayLibrary.AdafruitSh110x => ".clearDisplay();",
                _ => ".clear();",
            }).Append("\n}\n\n");
            o.Append("static void uiShow() {\n");
            if (!IsLcd)
            {
                o.Append("  ").Append(D).Append(_display.Library switch
                {
                    DisplayLibrary.U8g2 => ".sendBuffer();",
                    DisplayLibrary.GyverOled => ".update();",
                    _ => ".display();",
                }).Append('\n');
            }

            o.Append("}\n\n");
            if (HasValues)
            {
                o.Append("// A value's own cells: padded, so that a shorter one leaves nothing behind.\n");
                o.Append("static void uiPrintField(const char* text, uint8_t width) {\n  uint8_t used = 0;\n  while (text[used] != 0 && used < width) {\n    ").Append(D).Append(".print(text[used++]);\n  }\n");
                o.Append("  while (used++ < width) {\n    ").Append(D).Append(".print(' ');\n  }\n}\n\n");
            }
        }

        private int RowHeight(int size) => IsLcd ? 1 : 8 * size;

        private void Menus(StringBuilder o)
        {
            foreach (ScreenNode screen in document.Screens.Where(s => s.Menu is not null))
            {
                ScreenMenu menu = screen.Menu!;
                string id = Identifier(screen.Id);
                o.Append("static const __FlashStringHelper* uiItem_").Append(id).Append("(uint8_t index) {\n  switch (index) {\n");
                for (int i = 0; i < menu.Items.Count; i++)
                {
                    o.Append("    case ").Append(N(i)).Append(": return F(").Append(Literal(menu.Items[i].Text)).Append(");\n");
                }

                o.Append("    default: return F(\"\");\n  }\n}\n\n");
                o.Append("static void uiDrawMenu_").Append(id).Append("() {\n");
                for (int row = 0; row < menu.Rows; row++)
                {
                    o.Append("  uiAt(0, ").Append(N(menu.Top + (row * RowHeight(1)))).Append(", 1);\n");
                    o.Append("  if (uiMenuTop + ").Append(N(row)).Append(" < ").Append(N(menu.Items.Count)).Append(") {\n");
                    o.Append("    ").Append(D).Append(".print(uiMenuTop + ").Append(N(row)).Append(" == uiMenuIndex ? '>' : ' ');\n");
                    o.Append("    ").Append(D).Append(".print(uiItem_").Append(id).Append("(uiMenuTop + ").Append(N(row)).Append("));\n");
                    o.Append("  }\n");
                }

                o.Append("}\n\n");
            }
        }

        private void Drawing(StringBuilder o)
        {
            foreach (ScreenNode screen in document.Screens)
            {
                o.Append("// ").Append(screen.Title.Length > 0 ? screen.Title : screen.Id).Append('\n');
                o.Append("static void uiDraw_").Append(Identifier(screen.Id)).Append("() {\n");
                foreach (ScreenElement element in screen.Elements)
                {
                    Element(o, element);
                }

                if (screen.Menu is not null)
                {
                    o.Append("  uiDrawMenu_").Append(Identifier(screen.Id)).Append("();\n");
                }

                o.Append("}\n\n");
            }

            o.Append("static void uiDrawScreen() {\n  uiClear();\n  switch (uiScreen) {\n");
            foreach (ScreenNode screen in document.Screens)
            {
                o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n      uiDraw_").Append(Identifier(screen.Id)).Append("();\n      break;\n");
            }

            o.Append("    default:\n      break;\n  }\n  uiShow();\n}\n\n");
        }

        private void Element(StringBuilder o, ScreenElement element)
        {
            switch (element.Kind)
            {
                case ElementKind.Text:
                    o.Append("  uiAt(").Append(N(element.X)).Append(", ").Append(N(element.Y)).Append(", ").Append(N(element.Size)).Append(");\n");
                    o.Append("  ").Append(D).Append(".print(F(").Append(Literal(element.Text)).Append("));\n");
                    break;
                case ElementKind.Value:
                    ValueDraw(o, element, "  ");
                    break;
                case ElementKind.Line:
                    Shape(o, element, _display.Library switch
                    {
                        DisplayLibrary.U8g2 => $"drawLine({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)})",
                        DisplayLibrary.GyverOled => $"line({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)})",
                        _ => $"drawLine({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)}, {White})",
                    });
                    break;
                case ElementKind.Frame:
                    Shape(o, element, _display.Library switch
                    {
                        DisplayLibrary.U8g2 => $"drawFrame({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)})",
                        DisplayLibrary.GyverOled => $"rect({N(element.X)}, {N(element.Y)}, {N(element.X + element.Width - 1)}, {N(element.Y + element.Height - 1)}, OLED_STROKE)",
                        _ => $"drawRect({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)}, {White})",
                    });
                    break;
                case ElementKind.Box:
                    Shape(o, element, _display.Library switch
                    {
                        DisplayLibrary.U8g2 => $"drawBox({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)})",
                        DisplayLibrary.GyverOled => $"rect({N(element.X)}, {N(element.Y)}, {N(element.X + element.Width - 1)}, {N(element.Y + element.Height - 1)}, OLED_FILL)",
                        _ => $"fillRect({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)}, {White})",
                    });
                    break;
                default:
                    break;
            }
        }

        private string White => _display.Library == DisplayLibrary.AdafruitSh110x ? "SH110X_WHITE" : "SSD1306_WHITE";

        private void Shape(StringBuilder o, ScreenElement element, string call)
        {
            // A character display has no pixels to draw on; the editor does not offer shapes there.
            if (!IsLcd)
            {
                o.Append("  ").Append(D).Append('.').Append(call).Append(";\n");
            }
            else
            {
                o.Append("  // ").Append(element.Kind.ToString()).Append(": not on a character display\n");
            }
        }

        private static void ValueDraw(StringBuilder o, ScreenElement element, string indent)
        {
            int width = Math.Max(element.Width, 1);
            string hook = Identifier(element.Text);
            o.Append(indent).Append("{\n").Append(indent).Append("  char text[").Append(N(width + 1)).Append("] = \"\";\n");
            o.Append(indent).Append("  uiValue_").Append(hook).Append("(text, sizeof text);\n");
            o.Append(indent).Append("  uiAt(").Append(N(element.X)).Append(", ").Append(N(element.Y)).Append(", ").Append(N(element.Size)).Append(");\n");
            o.Append(indent).Append("  uiPrintField(text, ").Append(N(width)).Append(");\n").Append(indent).Append("}\n");
        }

        private void Values(StringBuilder o)
        {
            o.Append("// What changes on its own. A character display rewrites only these cells; an OLED, its whole buffer.\n");
            o.Append("static void uiDrawValues() {\n");
            if (IsLcd)
            {
                o.Append("  switch (uiScreen) {\n");
                foreach (ScreenNode screen in document.Screens.Where(s => s.Elements.Any(e => e.Kind == ElementKind.Value)))
                {
                    o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n");
                    foreach (ScreenElement value in screen.Elements.Where(e => e.Kind == ElementKind.Value))
                    {
                        ValueDraw(o, value, "      ");
                    }

                    o.Append("      break;\n");
                }

                o.Append("    default:\n      break;\n  }\n");
            }
            else
            {
                o.Append("  switch (uiScreen) {\n");
                foreach (ScreenNode screen in document.Screens.Where(s => s.Elements.Any(e => e.Kind == ElementKind.Value)))
                {
                    o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n      uiDrawScreen();\n      break;\n");
                }

                o.Append("    default:\n      break;\n  }\n");
            }

            o.Append("}\n\n");
        }

        private void Enter(StringBuilder o)
        {
            o.Append("static void uiEnter(UiScreen next) {\n  uiScreen = next;\n");
            if (HasTimeouts)
            {
                o.Append("  uiEnteredAt = millis();\n");
            }

            if (document.Screens.Any(s => s.Menu is not null))
            {
                o.Append("  uiMenuIndex = 0;\n  uiMenuTop = 0;\n");
            }

            o.Append("  uiDrawScreen();\n}\n\n");
            o.Append("void uiGoTo(UiScreen screen) {\n  uiEnter(screen);\n}\n\n");
            o.Append("void uiRedraw() {\n  uiDrawScreen();\n}\n\n");
            o.Append("UiScreen uiCurrent() {\n  return uiScreen;\n}\n\n");
        }

        private void Events2(StringBuilder o)
        {
            o.Append("void uiSend(UiEvent event) {\n  switch (uiScreen) {\n");
            foreach (ScreenNode screen in document.Screens)
            {
                var cases = new List<(string Event, string[] Body)>();
                if (screen.Menu is { } menu)
                {
                    int rows = menu.Rows;
                    if (menu.Up is { } up && EventName(up) is { } upName)
                    {
                        cases.Add((upName, ["if (uiMenuIndex > 0) {", "  uiMenuIndex--;", "  if (uiMenuIndex < uiMenuTop) {", "    uiMenuTop = uiMenuIndex;", "  }", "  uiDrawScreen();", "}"]));
                    }

                    if (menu.Down is { } down && EventName(down) is { } downName)
                    {
                        cases.Add((downName, [$"if (uiMenuIndex + 1 < {N(menu.Items.Count)}) {{", "  uiMenuIndex++;", $"  if (uiMenuIndex >= uiMenuTop + {N(rows)}) {{", $"    uiMenuTop = uiMenuIndex - {N(rows - 1)};", "  }", "  uiDrawScreen();", "}"]));
                    }

                    if (menu.Select is { } select && EventName(select) is { } selectName)
                    {
                        var body = new List<string> { "switch (uiMenuIndex) {" };
                        for (int i = 0; i < menu.Items.Count; i++)
                        {
                            ScreenMenuItem item = menu.Items[i];
                            if (item.Target.Length > 0)
                            {
                                body.Add($"  case {N(i)}: uiEnter(UI_{Upper(item.Target)}); break;");
                            }
                            else if (item.Action.Length > 0)
                            {
                                body.Add($"  case {N(i)}: uiAction_{Identifier(item.Action)}(); break;");
                            }
                        }

                        body.Add("  default: break;");
                        body.Add("}");
                        cases.Add((selectName, [.. body]));
                    }
                }

                foreach (ScreenTransition transition in screen.Transitions)
                {
                    if (EventName(transition.Trigger) is { } name && document.Find(transition.Target) is not null)
                    {
                        cases.Add((name, [$"uiEnter(UI_{Upper(transition.Target)});"]));
                    }
                }

                o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n");
                if (cases.Count > 0)
                {
                    o.Append("      switch (event) {\n");
                    foreach ((string name, string[] body) in cases.DistinctBy(c => c.Event))
                    {
                        o.Append("        case ").Append(name).Append(":\n");
                        foreach (string line in body)
                        {
                            o.Append("          ").Append(line).Append('\n');
                        }

                        o.Append("          return;\n");
                    }

                    o.Append("        default:\n          break;\n      }\n");
                }

                o.Append("      break;\n");
            }

            o.Append("    default:\n      break;\n  }\n");
            if (document.FromAnywhere.Count > 0)
            {
                o.Append("\n  // From any screen.\n  switch (event) {\n");
                foreach (ScreenTransition transition in document.FromAnywhere)
                {
                    if (EventName(transition.Trigger) is { } name && document.Find(transition.Target) is not null)
                    {
                        o.Append("    case ").Append(name).Append(":\n      uiEnter(UI_").Append(Upper(transition.Target)).Append(");\n      break;\n");
                    }
                }

                o.Append("    default:\n      break;\n  }\n");
            }
            else
            {
                o.Append("  (void)event;\n");
            }

            o.Append("}\n\n");
        }

        private void Inputs(StringBuilder o)
        {
            ScreenTrigger[] triggers = [.. AllTriggers];
            ScreenInput[] used = [.. wiring.Inputs.Where(i => triggers.Any(t => t.Part == i.Part))];
            foreach (ScreenInput input in used.Where(i => i.Kind == ScreenInputKind.Keypad))
            {
                string id = Identifier(input.Part);
                o.Append("static const char uiKeys_").Append(id).Append("[4][4] = {{'1', '2', '3', 'A'}, {'4', '5', '6', 'B'}, {'7', '8', '9', 'C'}, {'*', '0', '#', 'D'}};\n");
                o.Append("static byte uiRows_").Append(id).Append("[4] = {").Append(string.Join(", ", input.Pins.Take(4).Select(N))).Append("};\n");
                o.Append("static byte uiColumns_").Append(id).Append("[4] = {").Append(string.Join(", ", input.Pins.Skip(4).Take(4).Select(N))).Append("};\n");
                o.Append("static Keypad uiKeypad_").Append(id).Append("(makeKeymap(uiKeys_").Append(id).Append("), uiRows_").Append(id).Append(", uiColumns_").Append(id).Append(", 4, 4);\n\n");
            }

            // A press counts once, when it has held still for the debounce time.
            o.Append("struct UiButton {\n  uint8_t pin;\n  bool activeLow;\n  UiEvent event;\n  bool pressed;\n  bool raw;\n  uint32_t changedAt;\n};\n\n");
            var buttons = new List<(int Pin, bool ActiveLow, string Event)>();
            foreach (ScreenInput input in used)
            {
                if (input.Kind == ScreenInputKind.Button && triggers.Any(t => t.Kind == TriggerKind.Button && t.Part == input.Part))
                {
                    buttons.Add((input.Pins[0], input.ActiveLow, "UI_ON_" + Upper(input.Part)));
                }
                else if (input.Kind == ScreenInputKind.Encoder && input.Pins[2] >= 0 && triggers.Any(t => t.Kind == TriggerKind.EncoderPress && t.Part == input.Part))
                {
                    buttons.Add((input.Pins[2], true, "UI_ON_" + Upper(input.Part) + "_PRESS"));
                }
            }

            o.Append("static UiButton uiButtons[] = {\n");
            foreach ((int pin, bool activeLow, string name) in buttons)
            {
                o.Append("  {").Append(N(pin)).Append(", ").Append(activeLow ? "true" : "false").Append(", ").Append(name).Append(", false, false, 0},\n");
            }

            if (buttons.Count == 0)
            {
                o.Append("  {0, true, UI_NO_EVENT, false, false, 0},\n");
            }

            o.Append("};\nstatic const uint8_t uiButtonCount = ").Append(N(buttons.Count)).Append(";\n\n");
            o.Append("static void uiReadButtons() {\n  uint32_t now = millis();\n  for (uint8_t i = 0; i < uiButtonCount; i++) {\n    UiButton& button = uiButtons[i];\n");
            o.Append("    bool level = digitalRead(button.pin) == HIGH;\n    bool raw = button.activeLow ? !level : level;\n");
            o.Append("    if (raw != button.raw) {\n      button.raw = raw;\n      button.changedAt = now;\n    }\n");
            o.Append("    if (raw != button.pressed && now - button.changedAt >= ").Append(N(DebounceMs)).Append(") {\n      button.pressed = raw;\n      if (raw) {\n        uiSend(button.event);\n      }\n    }\n  }\n}\n\n");
            foreach (ScreenInput input in used.Where(i => i.Kind == ScreenInputKind.Encoder))
            {
                string id = Identifier(input.Part);
                o.Append("static void uiReadEncoder_").Append(id).Append("() {\n  static int last = HIGH;\n  int now = digitalRead(").Append(N(input.Pins[0])).Append(");\n");
                o.Append("  if (now == LOW && last == HIGH) {\n");
                o.Append("    uiSend(digitalRead(").Append(N(input.Pins[1])).Append(") == HIGH ? ").Append(triggers.Any(t => t.Kind == TriggerKind.EncoderRight && t.Part == input.Part) ? $"UI_ON_{Upper(input.Part)}_RIGHT" : "UI_NO_EVENT");
                o.Append(" : ").Append(triggers.Any(t => t.Kind == TriggerKind.EncoderLeft && t.Part == input.Part) ? $"UI_ON_{Upper(input.Part)}_LEFT" : "UI_NO_EVENT").Append(");\n  }\n  last = now;\n}\n\n");
            }
        }

        private void Begin(StringBuilder o)
        {
            o.Append("void uiBegin() {\n");
            if (!_display.Existing)
            {
                foreach (string line in BeginDisplay())
                {
                    o.Append("  ").Append(line).Append('\n');
                }
            }

            o.Append("  for (uint8_t i = 0; i < uiButtonCount; i++) {\n    pinMode(uiButtons[i].pin, uiButtons[i].activeLow ? INPUT_PULLUP : INPUT);\n  }\n");
            foreach (ScreenInput input in wiring.Inputs.Where(i => i.Kind == ScreenInputKind.Encoder && AllTriggers.Any(t => t.Part == i.Part)))
            {
                o.Append("  pinMode(").Append(N(input.Pins[0])).Append(", INPUT_PULLUP);\n  pinMode(").Append(N(input.Pins[1])).Append(", INPUT_PULLUP);\n");
            }

            o.Append("  uiEnter(uiScreen);\n}\n\n");
        }

        private void Update(StringBuilder o)
        {
            ScreenTrigger[] triggers = [.. AllTriggers];
            o.Append("void uiUpdate() {\n  uiReadButtons();\n");
            foreach (ScreenInput input in wiring.Inputs.Where(i => i.Kind == ScreenInputKind.Encoder && triggers.Any(t => t.Part == i.Part)))
            {
                o.Append("  uiReadEncoder_").Append(Identifier(input.Part)).Append("();\n");
            }

            foreach (ScreenInput input in wiring.Inputs.Where(i => i.Kind == ScreenInputKind.Keypad && triggers.Any(t => t.Part == i.Part)))
            {
                o.Append("  switch (uiKeypad_").Append(Identifier(input.Part)).Append(".getKey()) {\n");
                foreach (string key in triggers.Where(t => t.Kind == TriggerKind.Key && t.Part == input.Part).Select(t => t.Value).Distinct(StringComparer.Ordinal))
                {
                    o.Append("    case ").Append(CharLiteral(key)).Append(":\n      uiSend(UI_ON_KEY_").Append(KeyName(key)).Append(");\n      break;\n");
                }

                o.Append("    default:\n      break;\n  }\n");
            }

            if (HasTimeouts || HasValues)
            {
                o.Append("\n  uint32_t now = millis();\n");
            }

            if (HasTimeouts)
            {
                o.Append("  switch (uiScreen) {\n");
                foreach (ScreenNode screen in document.Screens)
                {
                    ScreenTransition? timed = screen.Transitions.FirstOrDefault(t => t.Trigger.Kind == TriggerKind.Timeout && document.Find(t.Target) is not null);
                    if (timed is not null && int.TryParse(timed.Trigger.Value, NumberStyles.Integer, CultureInfo.InvariantCulture, out int ms))
                    {
                        o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n      if (now - uiEnteredAt >= ").Append(N(ms)).Append("UL) {\n        uiEnter(UI_").Append(Upper(timed.Target)).Append(");\n      }\n      break;\n");
                    }
                }

                o.Append("    default:\n      break;\n  }\n");
            }

            if (HasValues)
            {
                o.Append("\n  if (now - uiValuesAt >= ").Append(N(RefreshMs)).Append("UL) {\n    uiValuesAt = now;\n    uiDrawValues();\n  }\n");
            }

            o.Append("}\n");
        }

        public string Hooks(string? existing)
        {
            var o = new StringBuilder(existing ?? "// Your part of the screens: what they show and what their menu items do.\n// ArduSim only ever adds to this file; what you write here stays.\n#include \"" + HeaderFile + "\"\n");
            string have = existing ?? "";
            foreach (string hook in ValueHooks)
            {
                if (!have.Contains("uiValue_" + hook + "(", StringComparison.Ordinal))
                {
                    o.Append("\n// The value \"").Append(hook).Append("\" on a screen: write at most size - 1 characters to out.\n");
                    o.Append("void uiValue_").Append(hook).Append("(char* out, uint8_t size) {\n  snprintf(out, size, \"--\");\n}\n");
                }
            }

            foreach (string hook in ActionHooks)
            {
                if (!have.Contains("uiAction_" + hook + "(", StringComparison.Ordinal))
                {
                    o.Append("\n// What the menu item \"").Append(hook).Append("\" does.\n");
                    o.Append("void uiAction_").Append(hook).Append("() {\n}\n");
                }
            }

            return o.ToString();
        }
    }

    /// <summary>What a sketch needs to call the generated code, as insertions; empty if it already does.</summary>
    /// <param name="existingDisplay">The sketch begins the display itself: <c>uiBegin()</c> goes after that, at the end of <c>setup</c>.</param>
    public static IReadOnlyList<(int Offset, string Text)> WiringEdits(string sketch, bool existingDisplay = false)
    {
        ArgumentNullException.ThrowIfNull(sketch);
        if (sketch.Contains("uiBegin", StringComparison.Ordinal))
        {
            return [];
        }

        var scan = new SketchScanner();
        scan.Add("", sketch);
        CodeFunction? setup = scan.Functions.FirstOrDefault(f => f.Name == "setup");
        CodeFunction? loop = scan.Functions.FirstOrDefault(f => f.Name == "loop");
        var edits = new List<(int, string)> { (0, "#include \"" + HeaderFile + "\"\n\n") };
        if (setup is null || loop is null)
        {
            edits.Add((sketch.Length, "\nvoid setup() {\n  uiBegin();\n}\n\nvoid loop() {\n  uiUpdate();\n}\n"));
            return edits;
        }

        if (existingDisplay)
        {
            int close = setup.Tokens[setup.BodyEnd].Offset;
            int lineStart = sketch.LastIndexOf('\n', Math.Max(close - 1, 0)) + 1;
            edits.Add(sketch.AsSpan(lineStart, close - lineStart).IsWhiteSpace() ? (lineStart, "  uiBegin();\n") : (close, "\n  uiBegin();\n"));
        }
        else
        {
            edits.Add((setup.Tokens[setup.BodyStart - 1].Offset + 1, "\n  uiBegin();"));
        }

        edits.Add((loop.Tokens[loop.BodyStart - 1].Offset + 1, "\n  uiUpdate();"));
        return edits;
    }
