        // The statement that gives a variable a value, within what it can hold.
        private string Assign(string target, string code)
        {
            switch (target)
            {
                case "clock":
                    Need(Piece.Clock);
                    Need(Piece.ClockSet);
                    return $"uiClockSet({code});";
                case "date":
                    Need(Piece.Clock);
                    Need(Piece.DateSet);
                    return $"uiDateSet({code});";
                default:
                    break;
            }

            if (Var(target) is not { } variable)
            {
                return "// nothing named " + target;
            }

            string save = variable.Saved ? " uiSave();" : "";
            if (variable.Saved)
            {
                Need(Piece.Save);
            }

            switch (variable.Kind)
            {
                case VariableKind.Stopwatch or VariableKind.Countdown:
                    Need(Piece.Timers);
                    return $"uiTimerSet(uiTimer_{target}, {code});";
                case VariableKind.Flag:
                    return $"uiVar_{target} = ({code}) ? 1 : 0;{save}";
                case VariableKind.Choice:
                    Need(Piece.Wrap);
                    return $"uiVar_{target} = uiWrap({code}, 0, {N(Math.Max(variable.Options.Count - 1, 0))});{save}";
                case VariableKind.Time:
                    Need(Piece.Wrap);
                    return $"uiVar_{target} = uiWrap({code}, 0, 86399L);{save}";
                default:
                    Need(variable.Wrap ? Piece.Wrap : Piece.Clamp);
                    return $"uiVar_{target} = {(variable.Wrap ? "uiWrap" : "uiClamp")}({code}, {Long(variable.Min)}, {Long(variable.Max)});{save}";
            }
        }

        private static string Long(int value) => value is > 32767 or < -32767 ? N(value) + "L" : N(value);

        // What an action says, in a function that returns a bool saying the event was taken.
        private IEnumerable<string> Steps(IEnumerable<ScreenAction> actions, ScreenNode? screen)
        {
            foreach (ScreenAction action in actions)
            {
                switch (action.Kind)
                {
                    case ActionKind.Set:
                        yield return Assign(action.Target, Expr(action.Value));
                        break;
                    case ActionKind.Add:
                        string current = ScreenExpression.Settable.Contains(action.Target) ? NameOf(action.Target) : Var(action.Target) is { } read ? ReadOf(read) : "0";
                        yield return Assign(action.Target, current + " + (" + Expr(action.Value) + ")");
                        break;
                    case ActionKind.Toggle:
                        if (Var(action.Target) is { Kind: VariableKind.Choice } choice)
                        {
                            yield return Assign(action.Target, $"(uiVar_{action.Target} + 1) % {N(Math.Max(choice.Options.Count, 1))}");
                        }
                        else if (Var(action.Target) is not null)
                        {
                            yield return Assign(action.Target, $"!uiVar_{action.Target}");
                        }

                        break;
                    case ActionKind.Start:
                        Need(Piece.Timers);
                        yield return $"uiStart(uiTimer_{action.Target});";
                        break;
                    case ActionKind.Stop:
                        Need(Piece.Timers);
                        yield return $"uiStop(uiTimer_{action.Target});";
                        break;
                    case ActionKind.StartStop:
                        Need(Piece.Timers);
                        yield return $"if (uiTimer_{action.Target}.running) {{ uiStop(uiTimer_{action.Target}); }} else {{ uiStart(uiTimer_{action.Target}); }}";
                        break;
                    case ActionKind.Reset:
                        Need(Piece.Timers);
                        yield return $"uiReset(uiTimer_{action.Target});";
                        break;
                    case ActionKind.InputCommit:
                        Need(Piece.Input);
                        if (screen is not null && InputOf(screen) is not null)
                        {
                            yield return $"if (!uiCommit_{Identifier(screen.Id)}()) {{";
                            yield return "  uiInputCount = 0;";
                            yield return "  uiDirty = true;";
                            yield return "  return true;";
                            yield return "}";
                        }

                        break;
                    case ActionKind.InputErase:
                        Need(Piece.Input);
                        yield return "if (uiInputCount > 0) { uiInputCount--; }";
                        break;
                    case ActionKind.InputClear:
                        Need(Piece.Input);
                        yield return "uiInputCount = 0;";
                        break;
                    case ActionKind.Beep:
                        if (_wiring.Outputs.FirstOrDefault(p => p.Part == action.Target) is { } buzzer)
                        {
                            (int hertz, int ms) = BeepOf(action.Value);
                            yield return $"tone({N(buzzer.Pin)}, {N(hertz)}, {N(ms)});";
                        }

                        break;
                    case ActionKind.Output:
                        if (_wiring.Outputs.FirstOrDefault(p => p.Part == action.Target) is { } output)
                        {
                            yield return $"digitalWrite({N(output.Pin)}, ({Expr(action.Value)}) ? HIGH : LOW);";
                        }

                        break;
                    case ActionKind.Hook:
                        if (action.Target.Length > 0)
                        {
                            yield return $"uiAction_{Identifier(action.Target)}();";
                        }

                        break;
                    default:
                        break;
                }
            }
        }

        /// <summary>A beep's value: hertz, then milliseconds.</summary>
        private static (int Hertz, int Ms) BeepOf(string value)
        {
            string[] parts = value.Split([' ', ','], StringSplitOptions.RemoveEmptyEntries);
            int hertz = parts.Length > 0 && int.TryParse(parts[0], NumberStyles.Integer, CultureInfo.InvariantCulture, out int h) ? h : 1000;
            int ms = parts.Length > 1 && int.TryParse(parts[1], NumberStyles.Integer, CultureInfo.InvariantCulture, out int m) ? m : 200;
            return (hertz, ms);
        }

        private List<string> Body(IEnumerable<ScreenAction> actions, string target, ScreenNode? screen)
        {
            var lines = new List<string>(Steps(actions, screen));
            if (target == ScreenDocument.Back)
            {
                lines.Add("uiBack();");
            }
            else if (_d.Find(target) is not null)
            {
                lines.Add($"uiEnter(UI_{Upper(target)});");
            }

            lines.Add("uiDirty = true;");
            return lines;
        }

        // ---- moving between screens ---------------------------------------------------------------------

        private void Enter(StringBuilder o)
        {
            // What arriving on a screen does. Coming back to one is not arriving.
            o.Append("static bool uiArrive() {\n");
            if (HasMenus && !UsesBack)
            {
                o.Append("  uiMenuIndex = 0;\n  uiMenuTop = 0;\n");
            }

            ScreenNode[] arrivals = [.. _d.Screens.Where(s => s.OnEnter.Count > 0 || InputOf(s) is not null)];
            if (arrivals.Length > 0)
            {
                o.Append("  switch (uiScreen) {\n");
                foreach (ScreenNode screen in arrivals)
                {
                    o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n");
                    if (InputOf(screen) is not null)
                    {
                        Need(Piece.Input);
                        o.Append("      uiInputCount = 0;\n");
                    }

                    foreach (string step in Steps(screen.OnEnter, screen))
                    {
                        o.Append("      ").Append(step).Append('\n');
                    }

                    o.Append("      break;\n");
                }

                o.Append("    default:\n      break;\n  }\n");
            }

            o.Append("  return true;\n}\n\n");
            if (UsesBack)
            {
                o.Append("// Where it came from, so that the way back is the way it came.\n");
                o.Append("struct UiVisit {\n  UiScreen screen;\n");
                if (HasMenus)
                {
                    o.Append("  uint8_t index;\n  uint8_t top;\n");
                }

                o.Append("};\n\nstatic const uint8_t UI_DEPTH = 8;\nstatic UiVisit uiVisits[UI_DEPTH];\nstatic uint8_t uiVisitCount;\n\n");
                string restore = "  uiScreen = uiVisits[uiVisitCount].screen;\n" + (HasMenus ? "  uiMenuIndex = uiVisits[uiVisitCount].index;\n  uiMenuTop = uiVisits[uiVisitCount].top;\n" : "");
                string timed = HasTimeouts ? "  uiEnteredAt = millis();\n" : "";
                o.Append("static void uiEnter(UiScreen next) {\n  if (next == uiScreen) {\n    uiDirty = true;\n    uiArrive();\n    return;\n  }\n\n  // A screen already on the way here is gone back to, so that the way never grows without end.\n");
                o.Append("  for (uint8_t i = uiVisitCount; i-- > 0;) {\n    if (uiVisits[i].screen == next) {\n      uiVisitCount = i;\n");
                o.Append("      uiScreen = next;\n").Append(HasMenus ? "      uiMenuIndex = uiVisits[i].index;\n      uiMenuTop = uiVisits[i].top;\n" : "").Append(HasTimeouts ? "      uiEnteredAt = millis();\n" : "");
                o.Append("      uiDirty = true;\n      return;\n    }\n  }\n\n");
                o.Append("  if (uiVisitCount == UI_DEPTH) {\n    memmove(uiVisits, uiVisits + 1, sizeof uiVisits - sizeof uiVisits[0]);\n    uiVisitCount--;\n  }\n\n");
                o.Append("  uiVisits[uiVisitCount].screen = uiScreen;\n");
                if (HasMenus)
                {
                    o.Append("  uiVisits[uiVisitCount].index = uiMenuIndex;\n  uiVisits[uiVisitCount].top = uiMenuTop;\n");
                }

                o.Append("  uiVisitCount++;\n  uiScreen = next;\n");
                if (HasMenus)
                {
                    o.Append("  uiMenuIndex = 0;\n  uiMenuTop = 0;\n");
                }

                o.Append(timed).Append("  uiDirty = true;\n  uiArrive();\n}\n\n");
                o.Append("void uiBack() {\n  if (uiVisitCount == 0) {\n    return;\n  }\n\n  uiVisitCount--;\n").Append(restore).Append(timed).Append("  uiDirty = true;\n}\n\n");
            }
            else
            {
                o.Append("static void uiEnter(UiScreen next) {\n  uiScreen = next;\n");
                if (HasTimeouts)
                {
                    o.Append("  uiEnteredAt = millis();\n");
                }

                o.Append("  uiDirty = true;\n  uiArrive();\n}\n\n");
            }

            o.Append("void uiGoTo(UiScreen screen) {\n  uiEnter(screen);\n}\n\n");
            o.Append("void uiRedraw() {\n  uiDirty = true;\n}\n\n");
            o.Append("UiScreen uiCurrent() {\n  return uiScreen;\n}\n\n");
        }

        private void Events2(StringBuilder o)
        {
            o.Append("// What an event does on each screen, then on any screen. True if something took it.\n");
            o.Append("static bool uiHandle(UiEvent event) {\n  switch (uiScreen) {\n");
            foreach (ScreenNode screen in _d.Screens)
            {
                var cases = new List<(string Event, string When, IReadOnlyList<string> Body)>();
                if (screen.Menu is { } menu)
                {
                    int rows = menu.Rows;
                    if (menu.Up is { } up && EventName(up) is { } upName)
                    {
                        cases.Add((upName, "", ["if (uiMenuIndex > 0) {", "  uiMenuIndex--;", "  if (uiMenuIndex < uiMenuTop) {", "    uiMenuTop = uiMenuIndex;", "  }", "  uiDirty = true;", "}"]));
                    }

                    if (menu.Down is { } down && EventName(down) is { } downName)
                    {
                        cases.Add((downName, "", [$"if (uiMenuIndex + 1 < {N(menu.Items.Count)}) {{", "  uiMenuIndex++;", $"  if (uiMenuIndex >= uiMenuTop + {N(rows)}) {{", $"    uiMenuTop = uiMenuIndex - {N(rows - 1)};", "  }", "  uiDirty = true;", "}"]));
                    }

                    if (menu.Select is { } select && EventName(select) is { } selectName)
                    {
                        var body = new List<string> { "switch (uiMenuIndex) {" };
                        for (int i = 0; i < menu.Items.Count; i++)
                        {
                            ScreenMenuItem item = menu.Items[i];
                            IEnumerable<ScreenAction> actions = item.Action.Length > 0 && item.Target.Length == 0 ? [.. item.Actions, new ScreenAction(ActionKind.Hook, item.Action)] : item.Actions;
                            List<string> lines = Body(actions, item.Target, screen);
                            if (lines.Count > 1)
                            {
                                body.Add($"  case {N(i)}:");
                                body.AddRange(lines.Select(line => "    " + line));
                                body.Add("    break;");
                            }
                        }

                        body.Add("  default: break;");
                        body.Add("}");
                        cases.Add((selectName, "", body));
                    }
                }

                foreach (ScreenTransition transition in screen.Transitions)
                {
                    if (EventName(transition.Trigger) is { } name)
                    {
                        cases.Add((name, transition.Trigger.When, Body(transition.Actions, transition.Target, screen)));
                    }
                }

                o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n");
                if (cases.Count > 0)
                {
                    o.Append("      switch (event) {\n");
                    WriteCases(o, cases, "        ");
                    o.Append("        default:\n          break;\n      }\n");
                }

                o.Append("      break;\n");
            }

            o.Append("    default:\n      break;\n  }\n");
            var anywhere = new List<(string Event, string When, IReadOnlyList<string> Body)>();
            foreach (ScreenTransition transition in _d.FromAnywhere)
            {
                if (EventName(transition.Trigger) is { } name)
                {
                    anywhere.Add((name, transition.Trigger.When, Body(transition.Actions, transition.Target, null)));
                }
            }

            if (anywhere.Count > 0)
            {
                o.Append("\n  // From any screen.\n  switch (event) {\n");
                WriteCases(o, anywhere, "    ");
                o.Append("    default:\n      break;\n  }\n");
            }
            else
            {
                o.Append("  (void)event;\n");
            }

            o.Append("  return false;\n}\n\n");
            o.Append("void uiSend(UiEvent event) {\n  uiHandle(event);\n}\n\n");
        }

        // One case per event. Transitions with a condition are tried in order; the first without one ends it.
        private void WriteCases(StringBuilder o, List<(string Event, string When, IReadOnlyList<string> Body)> cases, string indent)
        {
            foreach (IGrouping<string, (string Event, string When, IReadOnlyList<string> Body)> group in cases.GroupBy(c => c.Event, StringComparer.Ordinal))
            {
                o.Append(indent).Append("case ").Append(group.Key).Append(":\n");
                bool closed = false;
                foreach ((_, string when, IReadOnlyList<string> body) in group)
                {
                    if (closed)
                    {
                        break;
                    }

                    string extra = when.Length > 0 ? "  " : "";
                    if (when.Length > 0)
                    {
                        o.Append(indent).Append("  if (").Append(Expr(when)).Append(") {\n");
                    }

                    foreach (string line in body)
                    {
                        o.Append(indent).Append("  ").Append(extra).Append(line).Append('\n');
                    }

                    o.Append(indent).Append("  ").Append(extra).Append("return true;\n");
                    if (when.Length > 0)
                    {
                        o.Append(indent).Append("  }\n");
                    }
                    else
                    {
                        closed = true;
                    }
                }

                if (!closed)
                {
                    o.Append(indent).Append("  break;\n");
                }
            }
        }

        // ---- reading the inputs -------------------------------------------------------------------------

        private bool KeysGoSomewhere =>
            UsesAnyKey || _d.Screens.Any(s => s.KeyHook || InputOf(s) is not null);

        private ScreenInput[] KeypadsUsed =>
        [
            .. _wiring.Inputs.Where(i => i.Kind == ScreenInputKind.Keypad && (KeysGoSomewhere || AllTriggers.Any(t => t.Part == i.Part))),
        ];

        private bool UsesKeypads => KeypadsUsed.Length > 0;

        private void Inputs(StringBuilder o)
        {
            ScreenTrigger[] triggers = [.. AllTriggers];
            string press = UsesAnyKey ? "uiPress" : "uiSend";
            if (UsesAnyKey)
            {
                o.Append("// A press nothing on the screen took is still any key.\nstatic void uiPress(UiEvent event) {\n  if (!uiHandle(event)) {\n    uiHandle(UI_ON_ANY_KEY);\n  }\n}\n\n");
            }

            foreach (ScreenInput input in KeypadsUsed)
            {
                string id = Identifier(input.Part);
                o.Append("static const char uiKeys_").Append(id).Append("[4][4] = {{'1', '2', '3', 'A'}, {'4', '5', '6', 'B'}, {'7', '8', '9', 'C'}, {'*', '0', '#', 'D'}};\n");
                o.Append("static byte uiRows_").Append(id).Append("[4] = {").Append(string.Join(", ", input.Pins.Take(4).Select(N))).Append("};\n");
                o.Append("static byte uiColumns_").Append(id).Append("[4] = {").Append(string.Join(", ", input.Pins.Skip(4).Take(4).Select(N))).Append("};\n");
                o.Append("static Keypad uiKeypad_").Append(id).Append("(makeKeymap(uiKeys_").Append(id).Append("), uiRows_").Append(id).Append(", uiColumns_").Append(id).Append(", 4, 4);\n\n");
            }

            if (UsesKeypads)
            {
                KeyHandler(o, triggers);
            }

            // A press counts once, when it has held still for the debounce time.
            o.Append("struct UiButton {\n  uint8_t pin;\n  bool activeLow;\n  UiEvent event;\n  bool pressed;\n  bool raw;\n  uint32_t changedAt;\n};\n\n");
            var buttons = new List<(int Pin, bool ActiveLow, string Event)>();
            foreach (ScreenInput input in _wiring.Inputs)
            {
                if (input.Kind == ScreenInputKind.Button && triggers.Any(t => t.Kind == TriggerKind.Button && t.Part == input.Part))
                {
                    buttons.Add((input.Pins[0], input.ActiveLow, "UI_ON_" + Upper(input.Part)));
                }
                else if (input.Kind == ScreenInputKind.Button && UsesAnyKey)
                {
                    buttons.Add((input.Pins[0], input.ActiveLow, "UI_NO_EVENT"));
                }
                else if (input.Kind == ScreenInputKind.Encoder && input.Pins[2] >= 0 && triggers.Any(t => t.Kind == TriggerKind.EncoderPress && t.Part == input.Part))
                {
                    buttons.Add((input.Pins[2], true, "UI_ON_" + Upper(input.Part) + "_PRESS"));
                }
                else if (input.Kind == ScreenInputKind.Encoder && input.Pins[2] >= 0 && UsesAnyKey)
                {
                    buttons.Add((input.Pins[2], true, "UI_NO_EVENT"));
                }
            }

            o.Append("static UiButton uiButtons[] = {\n");
            foreach ((int pin, bool activeLow, string name) in buttons)
            {
                o.Append("  {").Append(N(pin)).Append(", ").Append(activeLow ? "true" : "false").Append(", ").Append(name).Append(", false, false, 0},\n");
            }

            if (buttons.Count == 0)
            {
                o.Append("  {0, true, UI_NO_EVENT, false, false, 0},\n");
            }

            o.Append("};\nstatic const uint8_t uiButtonCount = ").Append(N(buttons.Count)).Append(";\n\n");
            o.Append("static void uiReadButtons() {\n  uint32_t now = millis();\n  for (uint8_t i = 0; i < uiButtonCount; i++) {\n    UiButton& button = uiButtons[i];\n");
            o.Append("    bool level = digitalRead(button.pin) == HIGH;\n    bool raw = button.activeLow ? !level : level;\n");
            o.Append("    if (raw != button.raw) {\n      button.raw = raw;\n      button.changedAt = now;\n    }\n");
            o.Append("    if (raw != button.pressed && now - button.changedAt >= ").Append(N(DebounceMs)).Append(") {\n      button.pressed = raw;\n      if (raw) {\n        ").Append(press).Append("(button.event);\n      }\n    }\n  }\n}\n\n");
            foreach (ScreenInput input in _wiring.Inputs.Where(i => i.Kind == ScreenInputKind.Encoder && triggers.Any(t => t.Part == i.Part)))
            {
                string id = Identifier(input.Part);
                o.Append("static void uiReadEncoder_").Append(id).Append("() {\n  static int last = HIGH;\n  int now = digitalRead(").Append(N(input.Pins[0])).Append(");\n");
                o.Append("  if (now == LOW && last == HIGH) {\n");
                o.Append("    uiSend(digitalRead(").Append(N(input.Pins[1])).Append(") == HIGH ? ").Append(triggers.Any(t => t.Kind == TriggerKind.EncoderRight && t.Part == input.Part) ? $"UI_ON_{Upper(input.Part)}_RIGHT" : "UI_NO_EVENT");
                o.Append(" : ").Append(triggers.Any(t => t.Kind == TriggerKind.EncoderLeft && t.Part == input.Part) ? $"UI_ON_{Upper(input.Part)}_LEFT" : "UI_NO_EVENT").Append(");\n  }\n  last = now;\n}\n\n");
            }

            Conditions(o);
            Timeouts(o);
        }

        // A key goes first to what names it, then to the screen's input or its own code, and only then counts as any key.
        private void KeyHandler(StringBuilder o, ScreenTrigger[] triggers)
        {
            string[] keys = [.. triggers.Where(t => t.Kind == TriggerKind.Key).Select(t => t.Value).Distinct(StringComparer.Ordinal)];
            o.Append("static void uiOnKey(char key) {\n");
            if (keys.Length > 0)
            {
                o.Append("  switch (key) {\n");
                foreach (string key in keys)
                {
                    o.Append("    case ").Append(CharLiteral(key)).Append(":\n      if (uiHandle(UI_ON_KEY_").Append(KeyName(key)).Append(")) {\n        return;\n      }\n\n      break;\n");
                }

                o.Append("    default:\n      break;\n  }\n\n");
            }

            ScreenNode[] takers = [.. _d.Screens.Where(s => s.KeyHook || InputOf(s) is not null)];
            if (takers.Length > 0)
            {
                o.Append("  switch (uiScreen) {\n");
                foreach (ScreenNode screen in takers)
                {
                    o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n");
                    if (InputOf(screen) is { } input)
                    {
                        Need(Piece.Input);
                        Need(Piece.InputAdd);
                        o.Append("      if (key >= '0' && key <= '9') {\n        uiInputAdd(key, ").Append(N(DigitsOf(input))).Append(");\n        return;\n      }\n\n");
                    }

                    if (screen.KeyHook)
                    {
                        o.Append("      if (uiKey_").Append(Identifier(screen.Id)).Append("(key)) {\n        uiDirty = true;\n        return;\n      }\n\n");
                    }

                    o.Append("      break;\n");
                }

                o.Append("    default:\n      break;\n  }\n\n");
            }

            if (UsesAnyKey)
            {
                o.Append("  uiHandle(UI_ON_ANY_KEY);\n");
            }
            else if (keys.Length == 0 && takers.Length == 0)
            {
                o.Append("  (void)key;\n");
            }

            o.Append("}\n\n");
        }

        // A condition acts when it becomes true, once; not while it stays true, and not at the start if it already is.
        private void Conditions(StringBuilder o)
        {
            if (_conditions.Count == 0)
            {
                return;
            }

            o.Append("static void uiWatch() {\n  static bool started;\n  static bool was[").Append(N(_conditions.Count)).Append("];\n  bool now;\n");
            int index = 0;
            foreach ((string text, string name) in _conditions)
            {
                o.Append("\n  now = ").Append(Expr(text)).Append(";\n");
                o.Append("  if (started && now && !was[").Append(N(index)).Append("]) {\n    uiHandle(").Append(name).Append(");\n  }\n\n");
                o.Append("  was[").Append(N(index)).Append("] = now;\n");
                index++;
            }

            o.Append("  started = true;\n}\n\n");
        }

        private void Timeouts(StringBuilder o)
        {
            if (!HasTimeouts)
            {
                return;
            }

            o.Append("static bool uiTimeouts() {\n  uint32_t now = millis();\n  switch (uiScreen) {\n");
            foreach (ScreenNode screen in _d.Screens)
            {
                ScreenTransition? timed = screen.Transitions.FirstOrDefault(t => t.Trigger.Kind == TriggerKind.Timeout);
                if (timed is not null && int.TryParse(timed.Trigger.Value, NumberStyles.Integer, CultureInfo.InvariantCulture, out int ms))
                {
                    o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n      if (now - uiEnteredAt >= ").Append(N(ms)).Append("UL) {\n");
                    foreach (string line in Body(timed.Actions, timed.Target, screen))
                    {
                        o.Append("        ").Append(line).Append('\n');
                    }

                    // A timeout that leads nowhere starts counting again.
                    o.Append("        uiEnteredAt = now;\n        return true;\n      }\n\n      break;\n");
                }
            }

            o.Append("    default:\n      break;\n  }\n\n  return false;\n}\n\n");
        }

        private void Begin(StringBuilder o)
        {
            o.Append("void uiBegin() {\n");
            if (!_display.Existing)
            {
                foreach (string line in BeginDisplay())
                {
                    o.Append("  ").Append(line).Append('\n');
                }
            }

            if (IsLcd)
            {
                o.Append("  ").Append(D).Append(".clear();\n  memset(uiFrame, ' ', UI_CELLS);\n  memset(uiPanel, ' ', UI_CELLS);\n");
            }

            o.Append("  for (uint8_t i = 0; i < uiButtonCount; i++) {\n    pinMode(uiButtons[i].pin, uiButtons[i].activeLow ? INPUT_PULLUP : INPUT);\n  }\n");
            foreach (ScreenInput input in _wiring.Inputs.Where(i => i.Kind == ScreenInputKind.Encoder && AllTriggers.Any(t => t.Part == i.Part)))
            {
                o.Append("  pinMode(").Append(N(input.Pins[0])).Append(", INPUT_PULLUP);\n  pinMode(").Append(N(input.Pins[1])).Append(", INPUT_PULLUP);\n");
            }

            foreach (string part in AllActions.Where(a => a.Kind == ActionKind.Output).Select(a => a.Target).Distinct(StringComparer.Ordinal))
            {
                if (_wiring.Outputs.FirstOrDefault(p => p.Part == part) is { } output)
                {
                    o.Append("  pinMode(").Append(N(output.Pin)).Append(", OUTPUT);\n");
                }
            }

            if (Uses(Piece.Save))
            {
                o.Append("  uiLoadSaved();\n");
            }

            if (Uses(Piece.Clock))
            {
                o.Append("  uiClockBegin();\n");
            }

            if (HasTimeouts)
            {
                o.Append("  uiEnteredAt = millis();\n");
            }

            o.Append("  uiArrive();\n}\n\n");
        }

        private void Update(StringBuilder o)
        {
            ScreenTrigger[] triggers = [.. AllTriggers];
            o.Append("void uiUpdate() {\n");
            if (Uses(Piece.Clock))
            {
                o.Append("  uiClockTick();\n");
            }

            o.Append("  uiReadButtons();\n");
            foreach (ScreenInput input in _wiring.Inputs.Where(i => i.Kind == ScreenInputKind.Encoder && triggers.Any(t => t.Part == i.Part)))
            {
                o.Append("  uiReadEncoder_").Append(Identifier(input.Part)).Append("();\n");
            }

            foreach (ScreenInput input in KeypadsUsed)
            {
                o.Append("  {\n    char key = uiKeypad_").Append(Identifier(input.Part)).Append(".getKey();\n    if (key) {\n      uiOnKey(key);\n    }\n  }\n");
            }

            foreach (ScreenVariable variable in _d.Variables.Where(v => v.Kind == VariableKind.Countdown))
            {
                Need(Piece.Timers);
                string timer = "uiTimer_" + variable.Name;
                o.Append("\n  if (").Append(timer).Append(".running && uiRead(").Append(timer).Append(") == 0) {\n    ").Append(timer).Append(".running = false;\n    ").Append(timer).Append(".amount = 0;\n    uiDirty = true;\n");
                if (triggers.Any(t => t.Kind == TriggerKind.Finished && t.Value == variable.Name))
                {
                    o.Append("    uiHandle(UI_DONE_").Append(Upper(variable.Name)).Append(");\n");
                }

                o.Append("  }\n");
            }

            if (_conditions.Count > 0)
            {
                o.Append("\n  uiWatch();\n");
            }

            if (HasTimeouts)
            {
                o.Append("  uiTimeouts();\n");
            }

            ScreenNode[] ticking = [.. _d.Screens.Where(s => s.TickHook)];
            if (ticking.Length > 0)
            {
                o.Append("\n  switch (uiScreen) {\n");
                foreach (ScreenNode screen in ticking)
                {
                    o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n      uiTick_").Append(Identifier(screen.Id)).Append("();\n      break;\n");
                }

                o.Append("    default:\n      break;\n  }\n");
            }

            o.Append("\n  uint32_t now = millis();\n");
            if (IsLcd)
            {
                o.Append("  if (uiDirty || now - uiDrawnAt >= ").Append(N(LcdRefreshMs)).Append("UL) {\n    uiDirty = false;\n    uiDrawnAt = now;\n    uiDrawScreen();\n  }\n\n  uiFlush();\n}\n");
            }
            else
            {
                // Sending a whole buffer takes time: only what can change on its own is sent again.
                ScreenNode[] alive = [.. _d.Screens.Where(IsAlive)];
                o.Append("  bool due = false;\n");
                if (alive.Length > 0)
                {
                    o.Append("  switch (uiScreen) {\n");
                    foreach (ScreenNode screen in alive)
                    {
                        o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n");
                    }

                    o.Append("      due = now - uiDrawnAt >= ").Append(N(OledRefreshMs)).Append("UL;\n      break;\n    default:\n      break;\n  }\n\n");
                }

                o.Append("  if (uiDirty || due) {\n    uiDirty = false;\n    uiDrawnAt = now;\n    uiDrawScreen();\n  }\n}\n");
            }
        }

        private static bool IsAlive(ScreenNode screen) =>
            screen.Elements.Any(e => e.When.Length > 0 || e.Kind is ElementKind.Value or ElementKind.BigNumber or ElementKind.Bar or ElementKind.Input or ElementKind.Drawn)
            || screen.Menu?.Items.Any(i => i.Value.Length > 0 || i.Mark.Length > 0) == true;

        // ---- ui_hooks.cpp ----------------------------------------------------------------------------------

        public string Hooks(string? existing)
        {
            var o = new StringBuilder(existing ?? "// Your part of the screens: what they show and what their menu items do.\n// ArduSim only ever adds to this file; what you write here stays.\n#include \"" + HeaderFile + "\"\n");
            string have = existing ?? "";
            foreach (string hook in ValueHooks)
            {
                if (!have.Contains("uiValue_" + hook + "(", StringComparison.Ordinal))
                {
                    o.Append("\n// The value \"").Append(hook).Append("\" on a screen: write at most size - 1 characters to out.\n");
                    o.Append("void uiValue_").Append(hook).Append("(char* out, uint8_t size) {\n  snprintf(out, size, \"--\");\n}\n");
                }
            }

            foreach (string hook in ActionHooks)
            {
                if (!have.Contains("uiAction_" + hook + "(", StringComparison.Ordinal))
                {
                    o.Append("\n// What the action \"").Append(hook).Append("\" does.\n");
                    o.Append("void uiAction_").Append(hook).Append("() {\n}\n");
                }
            }

            foreach (string hook in DrawnHooks)
            {
                if (!have.Contains("uiCode_" + hook + "(", StringComparison.Ordinal))
                {
                    o.Append("\n// Draws \"").Append(hook).Append("\": uiAt(x, y) says where, uiOut.print(...) what. The cursor starts where the element lies.\n");
                    o.Append("void uiCode_").Append(hook).Append("() {\n}\n");
                }
            }

            foreach (ScreenNode screen in _d.Screens.Where(s => s.KeyHook))
            {
                string id = Identifier(screen.Id);
                if (!have.Contains("uiKey_" + id + "(", StringComparison.Ordinal))
                {
                    o.Append("\n// A key nothing else took on the screen \"").Append(screen.Id).Append("\". Return true if it did something: the screen is drawn again.\n");
                    o.Append("bool uiKey_").Append(id).Append("(char key) {\n  (void)key;\n  return false;\n}\n");
                }
            }

            foreach (ScreenNode screen in _d.Screens.Where(s => s.TickHook))
            {
                string id = Identifier(screen.Id);
                if (!have.Contains("uiTick_" + id + "(", StringComparison.Ordinal))
                {
                    o.Append("\n// Runs on every pass while the screen \"").Append(screen.Id).Append("\" shows.\n");
                    o.Append("void uiTick_").Append(id).Append("() {\n}\n");
                }
            }

            return o.ToString();
        }
    }

    /// <summary>What a sketch needs to call the generated code, as insertions; empty if it already does.</summary>
    /// <param name="existingDisplay">The sketch begins the display itself: <c>uiBegin()</c> goes after that, at the end of <c>setup</c>.</param>
    public static IReadOnlyList<(int Offset, string Text)> WiringEdits(string sketch, bool existingDisplay = false)
    {
        ArgumentNullException.ThrowIfNull(sketch);
        if (sketch.Contains("uiBegin", StringComparison.Ordinal))
        {
            return [];
        }

        var scan = new SketchScanner();
        scan.Add("", sketch);
        CodeFunction? setup = scan.Functions.FirstOrDefault(f => f.Name == "setup");
        CodeFunction? loop = scan.Functions.FirstOrDefault(f => f.Name == "loop");
        var edits = new List<(int, string)> { (0, "#include \"" + HeaderFile + "\"\n\n") };
        if (setup is null || loop is null)
        {
            edits.Add((sketch.Length, "\nvoid setup() {\n  uiBegin();\n}\n\nvoid loop() {\n  uiUpdate();\n}\n"));
            return edits;
        }

        if (existingDisplay)
        {
            int close = setup.Tokens[setup.BodyEnd].Offset;
            int lineStart = sketch.LastIndexOf('\n', Math.Max(close - 1, 0)) + 1;
            edits.Add(sketch.AsSpan(lineStart, close - lineStart).IsWhiteSpace() ? (lineStart, "  uiBegin();\n") : (close, "\n  uiBegin();\n"));
        }
        else
        {
            edits.Add((setup.Tokens[setup.BodyStart - 1].Offset + 1, "\n  uiBegin();"));
        }

        edits.Add((loop.Tokens[loop.BodyStart - 1].Offset + 1, "\n  uiUpdate();"));
        return edits;
    }
