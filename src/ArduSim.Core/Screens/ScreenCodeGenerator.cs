        // Turns what was typed on a screen into its variable; false if it makes no sense.
        private void InputCommits(StringBuilder o)
        {
            foreach (ScreenNode screen in _d.Screens)
            {
                if (InputOf(screen) is not { } input || !AllActionsOf(screen).Any(a => a.Kind == ActionKind.InputCommit))
                {
                    continue;
                }

                Need(Piece.Input);
                Need(Piece.InputNumber);
                int digits = DigitsOf(input);
                bool fromRight = input.Align == ElementAlign.Right;
                o.Append("static bool uiCommit_").Append(Identifier(screen.Id)).Append("() {\n");
                o.Append("  if (uiInputCount ").Append(fromRight ? "== 0" : "< " + N(digits)).Append(") {\n    return false;\n  }\n\n");
                string Digits(int first, int count) => $"uiInputNumber({N(first)}, {N(count)}, {N(digits)})";
                switch (input.Format)
                {
                    case ValueFormat.HourMinute:
                        o.Append("  int32_t hours = ").Append(Digits(0, 2)).Append(";\n  int32_t minutes = ").Append(Digits(2, 2)).Append(";\n");
                        o.Append("  if (hours > 23 || minutes > 59) {\n    return false;\n  }\n\n");
                        o.Append("  ").Append(Assign(input.Text, "hours * 3600 + minutes * 60")).Append('\n');
                        break;
                    case ValueFormat.HourMinuteSecond:
                        o.Append("  int32_t hours = ").Append(Digits(0, 2)).Append(";\n  int32_t minutes = ").Append(Digits(2, 2)).Append(";\n  int32_t seconds = ").Append(Digits(4, 2)).Append(";\n");
                        o.Append("  if (hours > 23 || minutes > 59 || seconds > 59) {\n    return false;\n  }\n\n");
                        o.Append("  ").Append(Assign(input.Text, "hours * 3600 + minutes * 60 + seconds")).Append('\n');
                        break;
                    case ValueFormat.MinuteSecond:
                        o.Append("  int32_t minutes = ").Append(Digits(0, 2)).Append(";\n  int32_t seconds = ").Append(Digits(2, 2)).Append(";\n");
                        o.Append("  if (seconds > 59) {\n    return false;\n  }\n\n");
                        o.Append("  ").Append(Assign(input.Text, "minutes * 60 + seconds")).Append('\n');
                        break;
                    case ValueFormat.DateDayFirst:
                    case ValueFormat.DateMonthFirst:
                    case ValueFormat.DateYearFirst:
                        Need(Piece.DaysIn);
                        (int dayAt, int monthAt, int yearAt) = input.Format switch
                        {
                            ValueFormat.DateDayFirst => (0, 2, 4),
                            ValueFormat.DateMonthFirst => (2, 0, 4),
                            _ => (6, 4, 0),
                        };
                        o.Append("  int32_t day = ").Append(Digits(dayAt, 2)).Append(";\n  int32_t month = ").Append(Digits(monthAt, 2)).Append(";\n  int32_t year = ").Append(Digits(yearAt, 4)).Append(";\n");
                        o.Append("  if (year < 2000 || month < 1 || month > 12 || day < 1 || day > uiDaysIn(year, month)) {\n    return false;\n  }\n\n");
                        o.Append("  ").Append(Assign(input.Text, "year * 10000 + month * 100 + day")).Append('\n');
                        break;
                    default:
                        o.Append("  int32_t number = ").Append(Digits(0, digits)).Append(";\n");
                        if (Var(input.Text) is { Kind: VariableKind.Number } limited)
                        {
                            o.Append("  if (number < ").Append(N(limited.Min)).Append(" || number > ").Append(N(limited.Max)).Append(") {\n    return false;\n  }\n\n");
                        }

                        o.Append("  ").Append(Assign(input.Text, "number")).Append('\n');
                        break;
                }

                o.Append("  return true;\n}\n\n");
            }
        }

        private static IEnumerable<ScreenAction> AllActionsOf(ScreenNode screen) =>
            screen.Transitions.SelectMany(t => t.Actions).Concat(screen.OnEnter).Concat(screen.Menu?.Items.SelectMany(i => i.Actions) ?? []);

