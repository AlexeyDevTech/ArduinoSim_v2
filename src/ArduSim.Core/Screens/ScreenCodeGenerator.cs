using System.Globalization;
using System.Text;

namespace ArduSim.Core.Screens;

/// <param name="Hooks">The whole of <c>ui_hooks.cpp</c>: what was there, plus the stubs that were missing.</param>
public sealed record GeneratedScreens(string Header, string Source, string Hooks);

/// <summary>
/// Plain, readable C++ from the model (ADR-019): a <c>switch</c> per screen for drawing and for events, no heap,
/// and only as much of a runtime as the project uses. The sketch calls <c>uiBegin()</c> and <c>uiUpdate()</c>.
/// </summary>
public static partial class ScreenCodeGenerator
{
    public const string HeaderFile = "ui_screens.h";
    public const string SourceFile = "ui_screens.cpp";
    public const string HooksFile = "ui_hooks.cpp";

    private const string Banner = "// Generated by ArduSim from screens.json: edit it on the Экраны tab. Changes made here are overwritten.\n";
    private const int LcdRefreshMs = 100;
    private const int OledRefreshMs = 250;
    private const int DebounceMs = 20;
    private const int FirstSymbol = 0x80;

    public static GeneratedScreens Generate(ScreenDocument document, ScreenWiring wiring, string? existingHooks)
    {
        ArgumentNullException.ThrowIfNull(document);
        ArgumentNullException.ThrowIfNull(wiring);
        var generator = new Generator(document, wiring, existingHooks ?? "");
        return new GeneratedScreens(generator.Header(), generator.Source(), generator.Hooks(existingHooks));
    }

    /// <summary>A C++ identifier from a name a person gave.</summary>
    public static string Identifier(string name)
    {
        ArgumentNullException.ThrowIfNull(name);
        var id = new StringBuilder(name.Length);
        foreach (char c in name)
        {
            id.Append(char.IsAsciiLetterOrDigit(c) ? c : '_');
        }

        return id.Length == 0 || char.IsAsciiDigit(id[0]) ? "s" + id : id.ToString();
    }

    private static string Upper(string name) => Identifier(name).ToUpperInvariant();

    private static string Literal(string text) => "\"" + ScreenCodeEdits.Escape(text, '"') + "\"";

    private static string CharLiteral(string text) => "'" + ScreenCodeEdits.Escape(text.Length > 0 ? text[..1] : " ", '\'') + "'";

    private static string N(int value) => value.ToString(CultureInfo.InvariantCulture);

    private sealed partial class Generator
    {
        private readonly ScreenDocument _d;
        private readonly ScreenWiring _wiring;
        private readonly ScreenDisplay _display;
        private readonly HashSet<string> _needed = new(StringComparer.Ordinal);
        private readonly List<string> _badExpressions = [];
        private readonly Dictionary<string, string> _conditions = new(StringComparer.Ordinal);
        private readonly List<SymbolEntry> _symbols = [];
        private readonly Dictionary<char, string> _letters = [];
        private readonly string _hooks;
        private readonly string _body;

        public Generator(ScreenDocument document, ScreenWiring wiring, string hooks)
        {
            _d = document;
            _wiring = wiring;
            _hooks = hooks;
            _display = document.Display;
            foreach (ScreenTransition transition in AllTransitions.Where(t => t.Trigger.Kind == TriggerKind.Condition))
            {
                if (!_conditions.ContainsKey(transition.Trigger.Value))
                {
                    _conditions[transition.Trigger.Value] = "UI_WHEN_" + N(_conditions.Count);
                }
            }

            CollectSymbols(hooks);
            if (_d.Variables.Any(v => v.Saved && v.Kind is not (VariableKind.Stopwatch or VariableKind.Countdown)))
            {
                Need(Piece.Save);
            }

            // Everything is written once now: what it uses decides which of the runtime's pieces go in, and the header needs to know too.
            var body = new StringBuilder();
            Menus(body);
            Drawing(body);
            InputCommits(body);
            Enter(body);
            Events2(body);
            Inputs(body);
            var update = new StringBuilder();
            Update(update);
            Begin(body);
            body.Append(update);
            _body = body.ToString();
        }

        private bool IsLcd => _display.Family == DisplayFamily.CharLcd;

        private string D => _display.Variable;

        private int RowStep => IsLcd ? 1 : 8;

        private int CellWide(int size) => IsLcd ? 1 : 6 * Math.Max(size, 1);

        private bool Uses(string piece) => _needed.Contains(piece);

        private void Need(string piece) => _needed.Add(piece);

        private bool HasTimeouts => _d.Screens.Any(s => s.Transitions.Any(t => t.Trigger.Kind == TriggerKind.Timeout));

        private bool HasMenus => _d.Screens.Any(s => s.Menu is not null);

        private IEnumerable<ScreenTransition> AllTransitions => _d.Screens.SelectMany(s => s.Transitions).Concat(_d.FromAnywhere);

        private IEnumerable<ScreenTrigger> AllTriggers =>
            AllTransitions.Select(t => t.Trigger).Concat(_d.Screens.Where(s => s.Menu is not null).SelectMany(s => new[] { s.Menu!.Up, s.Menu.Down, s.Menu.Select }).OfType<ScreenTrigger>());

        private bool UsesAnyKey => AllTriggers.Any(t => t.Kind == TriggerKind.AnyKey);

        private bool UsesBack => AllTransitions.Any(t => t.Target == ScreenDocument.Back)
            || _d.Screens.Any(s => s.Menu?.Items.Any(i => i.Target == ScreenDocument.Back) == true);

        private IEnumerable<ScreenAction> AllActions =>
            AllTransitions.SelectMany(t => t.Actions)
                .Concat(_d.Screens.SelectMany(s => s.OnEnter))
                .Concat(_d.Screens.SelectMany(s => s.Menu?.Items.SelectMany(i => i.Actions) ?? []));

        private static ScreenElement? InputOf(ScreenNode screen) => screen.Elements.FirstOrDefault(e => e.Kind == ElementKind.Input);

        private string? EventName(ScreenTrigger trigger) => trigger.Kind switch
        {
            TriggerKind.Button => "UI_ON_" + Upper(trigger.Part),
            TriggerKind.Key => "UI_ON_KEY_" + KeyName(trigger.Value),
            TriggerKind.EncoderLeft => "UI_ON_" + Upper(trigger.Part) + "_LEFT",
            TriggerKind.EncoderRight => "UI_ON_" + Upper(trigger.Part) + "_RIGHT",
            TriggerKind.EncoderPress => "UI_ON_" + Upper(trigger.Part) + "_PRESS",
            TriggerKind.Event => "UI_ON_" + Upper(trigger.Value),
            TriggerKind.AnyKey => "UI_ON_ANY_KEY",
            TriggerKind.Finished => "UI_DONE_" + Upper(trigger.Value),
            TriggerKind.Condition => _conditions[trigger.Value],
            _ => null,
        };

        private static string KeyName(string key) => key switch
        {
            "#" => "HASH",
            "*" => "STAR",
            _ => Upper(key),
        };

        private string[] Events => [.. AllTriggers.Select(EventName).OfType<string>().Distinct(StringComparer.Ordinal)];

        // ---- what the project calls in ui_hooks.cpp --------------------------------------------------

        // A name the project does not know is a hook; so is one that the hooks file already writes, whatever came to be built in since.
        private bool IsHook(string text) =>
            ScreenExpression.IsHookName(_d, text) || (text.Length > 0 && _hooks.Contains("uiValue_" + text + "(", StringComparison.Ordinal));

        private string[] ValueHooks =>
        [
            .. _d.Screens.SelectMany(s => s.Elements)
                .Where(e => e.Kind is ElementKind.Value or ElementKind.BigNumber && IsHook(e.Text))
                .Select(e => e.Text)
                .Concat(_d.Screens.SelectMany(s => s.Menu?.Items ?? []).Where(i => IsHook(i.Value)).Select(i => i.Value))
                .Select(Identifier)
                .Distinct(StringComparer.Ordinal),
        ];

        private string[] ActionHooks =>
        [
            .. _d.Screens.Where(s => s.Menu is not null).SelectMany(s => s.Menu!.Items).Where(i => i.Action.Length > 0).Select(i => i.Action)
                .Concat(AllActions.Where(a => a.Kind == ActionKind.Hook && a.Target.Length > 0).Select(a => a.Target))
                .Select(Identifier)
                .Distinct(StringComparer.Ordinal),
        ];

        private string[] DrawnHooks =>
        [
            .. _d.Screens.SelectMany(s => s.Elements).Where(e => e.Kind == ElementKind.Drawn).Select(e => Identifier(e.Text)).Distinct(StringComparer.Ordinal),
        ];

        // ---- the display's library -----------------------------------------------------------------

        private string DisplayType => _display.Existing && _display.TypeName.Length > 0 ? _display.TypeName : _display.Library switch
        {
            DisplayLibrary.LiquidCrystal => "LiquidCrystal",
            DisplayLibrary.LiquidCrystalI2c => "LiquidCrystal_I2C",
            DisplayLibrary.AdafruitSsd1306 => "Adafruit_SSD1306",
            DisplayLibrary.AdafruitSh110x => "Adafruit_SH1106G",
            DisplayLibrary.U8g2 => U8g2Type,
            _ => $"GyverOLED<{GyverModel}, OLED_BUFFER>",
        };

        private string U8g2Type
        {
            get
            {
                string controller = _wiring.Controller == "sh1106" ? "SH1106" : _wiring.Controller == "ssd1309" ? "SSD1309" : "SSD1306";
                string bus = _wiring.OledSpiPins.Count > 0 ? "4W_HW_SPI" : "HW_I2C";
                string panel = _wiring.Controller == "ssd1309" ? "NONAME0" : "NONAME";
                return $"U8G2_{controller}_{N(_display.Width)}X{N(_display.Height)}_{panel}_F_{bus}";
            }
        }

        private string GyverModel => _wiring.Controller == "sh1106" ? "SSH1106_128x64" : $"SSD1306_{N(_display.Width)}x{N(_display.Height)}";

        private string Include => _display.Library switch
        {
            DisplayLibrary.LiquidCrystal => "LiquidCrystal.h",
            DisplayLibrary.LiquidCrystalI2c => "LiquidCrystal_I2C.h",
            DisplayLibrary.AdafruitSsd1306 => "Adafruit_SSD1306.h",
            DisplayLibrary.AdafruitSh110x => "Adafruit_SH110X.h",
            DisplayLibrary.U8g2 => "U8g2lib.h",
            _ => "GyverOLED.h",
        };

        private string Construction()
        {
            string address = "0x" + _wiring.Address.ToString("X2", CultureInfo.InvariantCulture);
            bool spi = _wiring.OledSpiPins.Count == 3;
            int dc = spi ? _wiring.OledSpiPins[0] : -1;
            int reset = spi ? _wiring.OledSpiPins[1] : -1;
            int cs = spi ? _wiring.OledSpiPins[2] : -1;
            return _display.Library switch
            {
                DisplayLibrary.LiquidCrystal => $"{D}({string.Join(", ", _wiring.LcdPins.Select(N))})",
                DisplayLibrary.LiquidCrystalI2c => $"{D}({address}, {N(_display.Width)}, {N(_display.Height)})",
                DisplayLibrary.AdafruitSsd1306 when spi => $"{D}({N(_display.Width)}, {N(_display.Height)}, &SPI, {N(dc)}, {N(reset)}, {N(cs)})",
                DisplayLibrary.AdafruitSh110x when spi => $"{D}({N(_display.Width)}, {N(_display.Height)}, &SPI, {N(dc)}, {N(reset)}, {N(cs)})",
                DisplayLibrary.AdafruitSsd1306 or DisplayLibrary.AdafruitSh110x => $"{D}({N(_display.Width)}, {N(_display.Height)}, &Wire, -1)",
                DisplayLibrary.U8g2 when spi => $"{D}(U8G2_R0, {N(cs)}, {N(dc)}, {N(reset)})",
                DisplayLibrary.U8g2 => $"{D}(U8G2_R0, U8X8_PIN_NONE)",
                _ => D,
            };
        }

        private string[] BeginDisplay()
        {
            string address = "0x" + _wiring.Address.ToString("X2", CultureInfo.InvariantCulture);
            return _display.Library switch
            {
                DisplayLibrary.LiquidCrystal => [$"{D}.begin({N(_display.Width)}, {N(_display.Height)});"],
                DisplayLibrary.LiquidCrystalI2c => [$"{D}.init();", $"{D}.backlight();"],
                DisplayLibrary.AdafruitSsd1306 => [$"{D}.begin(SSD1306_SWITCHCAPVCC, {address});"],
                DisplayLibrary.AdafruitSh110x => [$"{D}.begin({address}, true);"],
                DisplayLibrary.U8g2 => [$"{D}.begin();"],
                _ => [$"{D}.init();"],
            };
        }

        // ---- the two files ---------------------------------------------------------------------------

        public string Header()
        {
            var o = new StringBuilder(Banner);
            o.Append("#pragma once\n#include <Arduino.h>\n");
            o.Append("#include <").Append(Include).Append(">\n\n");
            o.Append("enum UiScreen : uint8_t {\n");
            foreach (ScreenNode screen in _d.Screens)
            {
                o.Append("  UI_").Append(Upper(screen.Id)).Append(",\n");
            }

            o.Append("  UI_SCREEN_COUNT\n};\n\n");
            o.Append("enum UiEvent : uint8_t {\n  UI_NO_EVENT,\n");
            foreach (string name in Events)
            {
                o.Append("  ").Append(name).Append(",\n");
            }

            o.Append("};\n\n");
            o.Append("extern ").Append(DisplayType).Append(' ').Append(D).Append(";\n\n");
            o.Append("// Call uiBegin() from setup() and uiUpdate() from loop().\n");
            o.Append("void uiBegin();\nvoid uiUpdate();\n\n");
            o.Append("// For your own logic: go to a screen, send an event, redraw, ask where it is.\n");
            o.Append("void uiGoTo(UiScreen screen);\nvoid uiSend(UiEvent event);\nvoid uiRedraw();\nUiScreen uiCurrent();\n");
            if (UsesBack)
            {
                o.Append("void uiBack();\n");
            }

            o.Append("\n// For code that draws: where the next text goes, then uiOut.print(...). It takes UTF-8.\n");
            o.Append("class UiOut : public Print {\npublic:\n  size_t write(uint8_t ch) override;\n  using Print::write;\n};\n\nextern UiOut uiOut;\nvoid uiAt(int x, int y, int size = 1);\n");
            VariablesInHeader(o);
            string[] values = ValueHooks;
            string[] actions = ActionHooks;
            string[] drawn = DrawnHooks;
            ScreenNode[] keyHooks = [.. _d.Screens.Where(s => s.KeyHook)];
            ScreenNode[] tickHooks = [.. _d.Screens.Where(s => s.TickHook)];
            if (values.Length + actions.Length + drawn.Length + keyHooks.Length + tickHooks.Length > 0)
            {
                o.Append("\n// Written in ").Append(HooksFile).Append(": what the screens show and do.\n");
                foreach (string hook in values)
                {
                    o.Append("void uiValue_").Append(hook).Append("(char* out, uint8_t size);\n");
                }

                foreach (string hook in actions)
                {
                    o.Append("void uiAction_").Append(hook).Append("();\n");
                }

                foreach (string hook in drawn)
                {
                    o.Append("void uiCode_").Append(hook).Append("();\n");
                }

                foreach (ScreenNode screen in keyHooks)
                {
                    o.Append("bool uiKey_").Append(Identifier(screen.Id)).Append("(char key);\n");
                }

                foreach (ScreenNode screen in tickHooks)
                {
                    o.Append("void uiTick_").Append(Identifier(screen.Id)).Append("();\n");
                }
            }

            return o.ToString();
        }

        public string Source()
        {
            var o = new StringBuilder(Banner);
            o.Append("#include \"").Append(HeaderFile).Append("\"\n");
            if (UsesKeypads)
            {
                o.Append("#include <Keypad.h>\n");
            }

            if (Uses(Piece.Save))
            {
                o.Append("#include <EEPROM.h>\n");
            }

            if (Uses(Piece.Clock) && _wiring.HasRtc)
            {
                o.Append("#include <RTClib.h>\n");
            }

            foreach (string bad in _badExpressions.Distinct(StringComparer.Ordinal))
            {
                o.Append("#warning ").Append(Literal("This expression cannot be used, and counts as 0: " + bad)).Append('\n');
            }

            o.Append('\n');
            if (!_display.Existing)
            {
                o.Append(DisplayType).Append(' ').Append(Construction()).Append(";\n\n");
            }

            o.Append("static UiScreen uiScreen = UI_").Append(Upper(_d.Start)).Append(";\n");
            o.Append("static bool uiDirty = true;\nstatic uint32_t uiDrawnAt;\n");
            if (HasTimeouts)
            {
                o.Append("static uint32_t uiEnteredAt;\n");
            }

            if (HasMenus)
            {
                o.Append("static uint8_t uiMenuIndex;\nstatic uint8_t uiMenuTop;\n");
            }

            o.Append('\n');
            Runtime(o);
            o.Append(_body);
            return o.ToString();
        }

        // ---- what a piece of text takes ----------------------------------------------------------------

        // What the expression says in C++. One that makes no sense counts as 0, and the build says so.
        private string Expr(string text)
        {
            if (text.Trim().Length == 0 || !ScreenExpression.Check(_d, text).IsFine)
            {
                _badExpressions.Add(text);
                return "0";
            }

            return ScreenExpression.ToCode(text, NameOf);
        }

        private ScreenVariable? Var(string name) => _d.Variables.FirstOrDefault(v => v.Name == name);

        private string NameOf(string name)
        {
            switch (name)
            {
                case "true" or "false":
                    return name;
                case "hour" or "minute" or "second" or "day" or "month" or "year":
                    Need(Piece.Clock);
                    return "(int32_t)uiClock." + name;
                case "clock":
                    Need(Piece.Clock);
                    Need(Piece.ClockSeconds);
                    return "uiClockSeconds()";
                case "date":
                    Need(Piece.Clock);
                    Need(Piece.ClockDate);
                    return "uiClockDate()";
                case "weekday":
                    Need(Piece.Clock);
                    Need(Piece.Weekday);
                    return "uiWeekday()";
                case "uptime":
                    return "(int32_t)(millis() / 1000)";
                case "menuItem":
                    return HasMenus ? "(int32_t)(uiMenuIndex + 1)" : "0";
                case "menuCount":
                    Need(Piece.MenuCount);
                    return "uiMenuCount()";
                default:
                    break;
            }

            if (Var(name) is { } variable)
            {
                return ReadOf(variable);
            }

            string stem = name[..^3];
            Need(Piece.Timers);
            return name.EndsWith("_ms", StringComparison.Ordinal) ? $"(int32_t)uiRead(uiTimer_{stem})" : $"uiTimer_{stem}.running";
        }

        private string ReadOf(ScreenVariable variable)
        {
            switch (variable.Kind)
            {
                case VariableKind.Stopwatch:
                    Need(Piece.Timers);
                    return $"(int32_t)(uiRead(uiTimer_{variable.Name}) / 1000)";
                case VariableKind.Countdown:
                    Need(Piece.Timers);
                    return $"(int32_t)((uiRead(uiTimer_{variable.Name}) + 999) / 1000)";
                default:
                    return "uiVar_" + variable.Name;
            }
        }

        // Prints a text with the symbols it names.
        private void Say(StringBuilder o, string indent, string text)
        {
            foreach (ScreenFont.TextPart part in ScreenFont.Split(_d, text))
            {
                if (part.Letters is { } letters)
                {
                    o.Append(indent).Append("uiOut.print(F(").Append(Literal(letters)).Append("));\n");
                }
                else if (SymbolCode(part.Symbol!.Name) is { } code)
                {
                    o.Append(indent).Append("uiPut(").Append(code).Append(");\n");
                }
            }
        }

        // A value as words or digits, in the local buffer called text.
        private void FillText(StringBuilder o, string indent, string source, ValueFormat format, IReadOnlyList<string> words)
        {
            if (IsHook(source))
            {
                o.Append(indent).Append("uiValue_").Append(Identifier(source)).Append("(text, sizeof text);\n");
                return;
            }

            ScreenVariable? variable = Var(source);
            IReadOnlyList<string> list = format == ValueFormat.List ? words
                : format == ValueFormat.Auto && variable?.Kind is VariableKind.Flag or VariableKind.Choice ? variable.Options
                : [];
            string code = Expr(source);
            if (list.Count > 0)
            {
                Need(Piece.Copy);
                // A comparison can choose a word too: it counts as 0 or 1.
                o.Append(indent).Append("switch ((int32_t)(").Append(code).Append(")) {\n");
                for (int i = 0; i < list.Count; i++)
                {
                    o.Append(indent).Append("  case ").Append(N(i)).Append(": uiCopy(text, sizeof text, F(").Append(Literal(list[i])).Append(")); break;\n");
                }

                o.Append(indent).Append("  default: text[0] = 0; break;\n").Append(indent).Append("}\n");
                return;
            }

            ValueFormat shown = format != ValueFormat.Auto ? format : variable?.Kind switch
            {
                VariableKind.Time => ValueFormat.HourMinute,
                VariableKind.Stopwatch or VariableKind.Countdown => ValueFormat.MinuteSecond,
                _ => ValueFormat.Auto,
            };
            o.Append(indent);
            switch (shown)
            {
                case ValueFormat.TwoDigits:
                    o.Append("snprintf(text, sizeof text, \"%02ld\", (long)(").Append(code).Append("));\n");
                    break;
                case ValueFormat.HourMinute:
                    Need(Piece.Time);
                    o.Append("uiTextTime(text, sizeof text, ").Append(code).Append(", true, false);\n");
                    break;
                case ValueFormat.HourMinuteSecond:
                    Need(Piece.Time);
                    o.Append("uiTextTime(text, sizeof text, ").Append(code).Append(", true, true);\n");
                    break;
                case ValueFormat.MinuteSecond:
                    Need(Piece.Time);
                    o.Append("uiTextTime(text, sizeof text, ").Append(code).Append(", false, true);\n");
                    break;
                case ValueFormat.MinuteSecondCentis:
                    o.Append("{\n").Append(indent).Append("  int32_t ms = ").Append(code).Append(";\n");
                    o.Append(indent).Append("  snprintf(text, sizeof text, \"%02ld:%02ld.%02ld\", (long)(ms / 60000), (long)(ms / 1000 % 60), (long)(ms / 10 % 100));\n").Append(indent).Append("}\n");
                    break;
                case ValueFormat.DateDayFirst:
                case ValueFormat.DateMonthFirst:
                case ValueFormat.DateYearFirst:
                    Need(Piece.Date);
                    o.Append("uiTextDate(text, sizeof text, ").Append(code).Append(", ").Append(N(shown - ValueFormat.DateDayFirst)).Append(");\n");
                    break;
                default:
                    o.Append("snprintf(text, sizeof text, \"%ld\", (long)(").Append(code).Append("));\n");
                    break;
            }
        }

        private static string AlignName(ElementAlign align) => align switch
        {
            ElementAlign.Center => "UI_CENTER",
            ElementAlign.Right => "UI_RIGHT",
            _ => "UI_LEFT",
        };

        // A field's width in cells: what it says, or to the display's edge.
        private int FieldOf(ScreenElement element) =>
            element.Width > 0 ? element.Width : Math.Max(1, (_display.Width - element.X) / CellWide(element.Size));

        // ---- menus -----------------------------------------------------------------------------------

        private void Menus(StringBuilder o)
        {
            foreach (ScreenNode screen in _d.Screens.Where(s => s.Menu is not null))
            {
                ScreenMenu menu = screen.Menu!;
                string id = Identifier(screen.Id);
                int across = _display.Width / CellWide(1);
                o.Append("static void uiSayItem_").Append(id).Append("(uint8_t index) {\n  switch (index) {\n");
                for (int i = 0; i < menu.Items.Count; i++)
                {
                    o.Append("    case ").Append(N(i)).Append(":\n");
                    Say(o, "      ", menu.Items[i].Text);
                    o.Append("      break;\n");
                }

                o.Append("    default:\n      break;\n  }\n}\n\n");
                bool hasRight = menu.Items.Any(i => i.Value.Length > 0 || i.Mark.Length > 0);
                if (hasRight)
                {
                    Need(Piece.Place);
                    o.Append("// What an item shows at its row's right edge.\n");
                    o.Append("static void uiItemRight_").Append(id).Append("(uint8_t index, int y) {\n  switch (index) {\n");
                    for (int i = 0; i < menu.Items.Count; i++)
                    {
                        ScreenMenuItem item = menu.Items[i];
                        if (item.Value.Length == 0 && item.Mark.Length == 0)
                        {
                            continue;
                        }

                        o.Append("    case ").Append(N(i)).Append(": {\n");
                        if (item.Value.Length > 0)
                        {
                            o.Append("      char text[").Append(N((2 * across) + 1)).Append("] = \"\";\n");
                            FillText(o, "      ", item.Value, item.Format, []);
                            o.Append("      uiPlace(0, y, 1, ").Append(N(across)).Append(", UI_RIGHT, text);\n");
                        }

                        if (item.Mark.Length > 0)
                        {
                            o.Append("      if (").Append(Expr(item.Mark)).Append(") {\n        uiPlace(0, y, 1, ").Append(N(across)).Append(", UI_RIGHT, \"*\");\n      }\n");
                        }

                        o.Append("      break;\n    }\n");
                    }

                    o.Append("    default:\n      break;\n  }\n}\n\n");
                }

                string marker = menu.Marker.Length > 0 ? menu.Marker : ">";
                int markerCells = ScreenFont.CellsOf(_d, marker);
                o.Append("static void uiDrawMenu_").Append(id).Append("() {\n");
                if (menu.Counter && menu.Top - RowStep >= 0)
                {
                    Need(Piece.Place);
                    o.Append("  {\n    char text[8];\n    snprintf(text, sizeof text, \"%d/%d\", uiMenuIndex + 1, ").Append(N(menu.Items.Count)).Append(");\n");
                    o.Append("    uiPlace(0, ").Append(N(menu.Top - RowStep)).Append(", 1, ").Append(N(across)).Append(", UI_RIGHT, text);\n  }\n");
                }

                for (int row = 0; row < menu.Rows; row++)
                {
                    string index = "uiMenuTop + " + N(row);
                    int y = menu.Top + (row * RowStep);
                    o.Append("  if (").Append(index).Append(" < ").Append(N(menu.Items.Count)).Append(") {\n");
                    o.Append("    uiAt(0, ").Append(N(y)).Append(", 1);\n");
                    o.Append("    if (").Append(index).Append(" == uiMenuIndex) {\n");
                    Say(o, "      ", marker);
                    o.Append("    } else {\n      uiOut.print(F(").Append(Literal(new string(' ', markerCells))).Append("));\n    }\n");
                    o.Append("    uiSayItem_").Append(id).Append('(').Append(index).Append(");\n");
                    if (hasRight)
                    {
                        o.Append("    uiItemRight_").Append(id).Append('(').Append(index).Append(", ").Append(N(y)).Append(");\n");
                    }

                    o.Append("  }\n");
                }

                o.Append("}\n\n");
            }
        }

        // ---- what a screen draws -----------------------------------------------------------------------

        private void Drawing(StringBuilder o)
        {
            foreach (ScreenNode screen in _d.Screens)
            {
                o.Append("// ").Append(screen.Title.Length > 0 ? screen.Title : screen.Id).Append('\n');
                o.Append("static void uiDraw_").Append(Identifier(screen.Id)).Append("() {\n");
                foreach (ScreenElement element in screen.Elements)
                {
                    bool guarded = element.When.Length > 0;
                    if (guarded)
                    {
                        o.Append("  if (").Append(Expr(element.When)).Append(") {\n");
                    }

                    var inner = new StringBuilder();
                    Element(inner, element);
                    o.Append(guarded ? Indented(inner.ToString()) : inner.ToString());
                    if (guarded)
                    {
                        o.Append("  }\n");
                    }
                }

                if (screen.Menu is not null)
                {
                    o.Append("  uiDrawMenu_").Append(Identifier(screen.Id)).Append("();\n");
                }

                o.Append("}\n\n");
            }

            o.Append("static void uiDrawScreen() {\n  uiClear();\n  switch (uiScreen) {\n");
            foreach (ScreenNode screen in _d.Screens)
            {
                o.Append("    case UI_").Append(Upper(screen.Id)).Append(":\n      uiDraw_").Append(Identifier(screen.Id)).Append("();\n      break;\n");
            }

            o.Append("    default:\n      break;\n  }\n  uiShow();\n}\n\n");
        }

        private static string Indented(string lines) =>
            string.Concat(lines.Split('\n', StringSplitOptions.RemoveEmptyEntries).Select(line => "  " + line + "\n"));

        private void Element(StringBuilder o, ScreenElement element)
        {
            switch (element.Kind)
            {
                case ElementKind.Text:
                    int cells = ScreenFont.CellsOf(_d, element.Text);
                    int free = Math.Max(FieldOf(element) - cells, 0);
                    int shift = element.Align switch
                    {
                        ElementAlign.Center => free / 2,
                        ElementAlign.Right => free,
                        _ => 0,
                    };
                    o.Append("  uiAt(").Append(N(element.X + (shift * CellWide(element.Size)))).Append(", ").Append(N(element.Y)).Append(", ").Append(N(element.Size)).Append(");\n");
                    Say(o, "  ", element.Text);
                    break;
                case ElementKind.Value:
                    ValueDraw(o, element);
                    break;
                case ElementKind.BigNumber:
                    BigDraw(o, element);
                    break;
                case ElementKind.Bar:
                    BarDraw(o, element);
                    break;
                case ElementKind.Symbol:
                    if (SymbolCode(element.Text) is { } symbol)
                    {
                        o.Append("  uiAt(").Append(N(element.X)).Append(", ").Append(N(element.Y)).Append(", ").Append(N(element.Size)).Append(");\n");
                        o.Append("  uiPut(").Append(symbol).Append(");\n");
                    }

                    break;
                case ElementKind.Input:
                    InputDraw(o, element);
                    break;
                case ElementKind.Drawn:
                    o.Append("  uiAt(").Append(N(element.X)).Append(", ").Append(N(element.Y)).Append(", ").Append(N(element.Size)).Append(");\n");
                    o.Append("  uiCode_").Append(Identifier(element.Text)).Append("();\n");
                    break;
                case ElementKind.Line:
                    Shape(o, element, _display.Library switch
                    {
                        DisplayLibrary.U8g2 => $"drawLine({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)})",
                        DisplayLibrary.GyverOled => $"line({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)})",
                        _ => $"drawLine({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)}, {White})",
                    });
                    break;
                case ElementKind.Frame:
                    Shape(o, element, _display.Library switch
                    {
                        DisplayLibrary.U8g2 => $"drawFrame({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)})",
                        DisplayLibrary.GyverOled => $"rect({N(element.X)}, {N(element.Y)}, {N(element.X + element.Width - 1)}, {N(element.Y + element.Height - 1)}, OLED_STROKE)",
                        _ => $"drawRect({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)}, {White})",
                    });
                    break;
                case ElementKind.Box:
                    Shape(o, element, _display.Library switch
                    {
                        DisplayLibrary.U8g2 => $"drawBox({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)})",
                        DisplayLibrary.GyverOled => $"rect({N(element.X)}, {N(element.Y)}, {N(element.X + element.Width - 1)}, {N(element.Y + element.Height - 1)}, OLED_FILL)",
                        _ => $"fillRect({N(element.X)}, {N(element.Y)}, {N(element.Width)}, {N(element.Height)}, {White})",
                    });
                    break;
                default:
                    break;
            }
        }

